    e('    .o_evt_susp      (w_evt_susp),')
    e('    .o_evt_resume    (w_evt_resume),')
    e('    .o_evt_conn      (w_evt_conn),')
    e('    .o_evt_disc      (w_evt_disc),')
    e('    .o_evt_role      (w_evt_role),')
    e('    .o_evt_enum      (w_evt_enum),')
    e('    .o_clr_rmt_wake  (w_clr_rmt_wake),')
