    e('  endgenerate')
    e()

    # ----------------------------------------------------------------- fifo
    e('  // Region configuration of the FIFO manager: the start (low half) and size (high half) words.')
    e('  always_comb begin : p_com_regions')
    e("    w_q_base = '0;")
    e("    w_q_size = '0;")
    e('    w_q_base[15:0] = w_ph_fifo_rx[15:0];')
    e('    w_q_size[15:0] = w_ph_fifo_rx[31:16];')
    e('    for (int idx = 0; idx < LPARA_NEP1; idx++) begin')
    e('      w_q_base[(idx + 1)*16 +: 16] = w_ph_epi_buf[idx][15:0];')
    e('      w_q_size[(idx + 1)*16 +: 16] = w_ph_epi_buf[idx][31:16];')
    e('    end')
    e('    w_q_base[(LPARA_NQ - 2)*16 +: 16] = w_ph_fifo_hnp[15:0];')
    e('    w_q_size[(LPARA_NQ - 2)*16 +: 16] = w_ph_fifo_hnp[31:16];')
