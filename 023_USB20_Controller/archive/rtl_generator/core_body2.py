    e('    .o_clr_port_susp (w_clr_port_susp),')
    e('    .o_clr_port_res  (w_clr_port_res),')
    e('    .i_hlpm_ack      (w_host_lpm_ack),')
    e('    .i_lpm_vld       (w_dev_lpm_vld),')
    e('    .i_lpm_hird      (w_dev_lpm_hird),')
    e('    .i_lpm_rw        (w_dev_lpm_rw),')
    e('    .o_lpm_hird      (w_spd_lpm_hird),')
    e('    .o_lpm_rw        (w_spd_lpm_rw)')
