    e('  endgenerate')
    e()

    # ----------------------------------------------------------------- host engine
    e('  // Host engine (builds with a host or a dual role).')
    e('  generate')
    e("    if (PARA_USB2_ROLE != 32'd0) begin : gen_host")
    e('      m_usb2_host #(')
    e('        .PARA_USB2_NHC    (PARA_USB2_NUM_HC),')
    e('        .PARA_USB2_UTMI_W (PARA_USB2_UTMI_W),')
    e('        .PARA_USB2_HQ_NP  (LPARA_HQ_NP),')
    e('        .PARA_USB2_TSCALE (PARA_USB2_TSCALE)')
    e('      ) u_host (')
    e('        .i_clk_phy       (i_clk_phy),')
    e('        .i_rst_n_core    (w_rst_n_core),')
    e('        .i_host_act      (w_host_act),')
    e('        .i_port_speed    (w_speed),')
    for n in ('hs_vld', 'hs_pid', 'dat_sop', 'dat_pid', 'dat_n', 'dat_b', 'dat_end', 'dat_ok', 'dat_len'):
        e(f'        .i_{n} (w_{n}),')
    for n in ('tx_req', 'tx_kind', 'tx_pid', 'tx_fld', 'tx_len'):
        e(f'        .o_{n} (w_host_{n}),')
    e('        .i_tx_done       (w_tx_done),')
    e('        .i_tx_fail       (w_tx_fail),')
