    e("      reg_flc_seen   <= 2'b00;")
    e("      reg_lpclr_seen <= 1'b0;")
    e("      reg_acc_seen   <= 1'b0;")
    e('    end else begin')
    e('      reg_flc_seen   <= w_ph_fifo_ctl[1:0];')
    e('      reg_lpclr_seen <= w_ph_lpbk_sts[24];')
    e('      reg_acc_seen   <= w_ph_phy_acc[25];')
    e('    end')
    e('  end')
    e()
    e('  assign w_fl_rx      = w_ph_fifo_ctl[0] & ~reg_flc_seen[0];')
    e('  assign w_fl_tx      = w_ph_fifo_ctl[1] & ~reg_flc_seen[1];')
    e('  assign w_flush_vld  = w_fl_rx | w_fl_tx;')
    e('  // u2_fifo_ctl.tx_sel names a device IN endpoint (0 to 15) or a host region (10h, 11h); the FIFO')
    e('  // queues are numbered receive 0, IN endpoint n = n + 1, host non-periodic and periodic last (BUG-025).')
    e("  assign w_txq_phy    = w_ph_fifo_ctl[6] ? (LPARA_NQ[4:0] - 5'd2 + {4'd0, w_ph_fifo_ctl[2]}) : ({1'b0, w_ph_fifo_ctl[5:2]} + 5'd1);")
    e("  assign w_txq_bus    = w_bus_fifo_ctl[6] ? (LPARA_NQ[4:0] - 5'd2 + {4'd0, w_bus_fifo_ctl[2]}) : ({1'b0, w_bus_fifo_ctl[5:2]} + 5'd1);")
    e("  assign w_flush_q    = w_fl_rx ? 5'd0 : w_txq_phy;")
    e('  assign w_lpclr_edge = w_ph_lpbk_sts[24] & ~reg_lpclr_seen;')
    e('  assign w_acc_edge   = w_ph_phy_acc[25] & ~reg_acc_seen;')
    e('  assign w_reg_start  = w_acc_edge;')
    e()
    e('  // Packet port: the engine of the active role drives it; the idle engine drives zeros.')
    e('  assign w_rxw_sop    = w_dev_rxw_sop | w_host_rxw_sop;')
    e('  assign w_rxw_end    = w_dev_rxw_end | w_host_rxw_end;')
    e('  assign w_rxw_tag    = w_role_host ? w_host_rxw_tag : w_dev_rxw_tag;')
    e('  assign w_rxw_n      = w_role_host ? w_host_rxw_n : w_dev_rxw_n;')
    e('  assign w_rxw_b      = w_role_host ? w_host_rxw_b : w_dev_rxw_b;')
    e('  assign w_rxw_ok     = w_role_host ? w_host_rxw_ok : w_dev_rxw_ok;')
    e('  assign w_rxw_len    = w_role_host ? w_host_rxw_len : w_dev_rxw_len;')
    e('  assign w_txr_start  = w_dev_txr_start | w_host_txr_start;')
    e('  assign w_txr_commit = w_dev_txr_commit | w_host_txr_commit;')
