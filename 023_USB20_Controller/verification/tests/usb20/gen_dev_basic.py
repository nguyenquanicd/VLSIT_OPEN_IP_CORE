"""Infrastructure check scenario (not a plan test): SETUP, bulk OUT and bulk IN on a device without bus reset.
Expected values from REQ-FUNC-001, 004, 027, 031 and the programming flow S06 to S13 of section 11.2."""
import sys
from usb2lib import *

s = Scn('dev_basic', seed=int(sys.argv[1]) if len(sys.argv) > 1 else 1)
d = DevModel(s, address=5)
s.r('version', major=1)
s.w('fifo_rx', start=0, size=128)
s.w('epi_buf', 0, start=128, size=16)
s.w('epi_buf', 1, start=144, size=64)
s.w('dctrl', dev_addr=5, soft_conn=1)
s.w('dma_cfg', burst_len=16)
s.w('epo_dma', 0, addr=0x100)
s.w('epo_dma', 1, addr=0x200)
s.w('epi_dma', 1, addr=0x400)
s.wraw('irq_en', 0, 0x01FFFFFF)
s.w('ctrl', core_en=1, dma_en=1, ahb_err_stop=1)
s.idle_bus(400)
setup = s.rnd(8)
d.setup(0, setup)
s.idle_bus(800)
s.mc(0x100, setup)
s.r('epo_int', 0, setup=1)
s.bin('cg_toggle.setup')
# bulk OUT of two 64-byte packets on endpoint 1
s.w('epo_xfr', 1, xsize=128, pkt_cnt=2)
s.w('epo_ctl', 1, mps=64, type=BULK, ep_en=1)
s.idle(400)
p1, p2 = s.rnd(64), s.rnd(64)
d.out(1, p1)
s.idle(100)
d.out(1, p2)
s.idle_bus(1500)
s.mc(0x200, p1 + p2)
s.r('epo_int', 1, done=1)
s.r('epo_xfr', 1, xsize=0)
s.bin('cg_toggle.d0'); s.bin('cg_toggle.d1')
# IN on an endpoint that is not armed: NAK
d.in_(1, expect=NAK)
# bulk IN of 40 bytes
pin = s.rnd(40)
s.mw(0x400, pin)
s.w('epi_xfr', 1, xsize=40, pkt_cnt=1)
s.w('epi_ctl', 1, mps=64, type=BULK, ep_en=1)
s.idle_bus(3000)
d.in_(1, pin)
s.idle_bus(2000)
s.r('epi_int', 1, done=1)
s.save('ops/dev_basic.ops')
