"""SLH-DSA verification (FIPS 205 Algorithm 24, pure form) as a program of the hash-tree processor.
Register map: R0 n, R1 h', R2 d, R3 a, R4 k, R5 len, R6 m, R7 hash length of the MGF, R8 pad of F, R9 pad of H and T_l,
R10..R15 address (layer, tree, type, key pair, chain or height, hash or index), R16..R18 call arguments (address of the
input, destination, length), R19 signature pointer, R20 idx_tree, R21 idx_leaf, R22..R30 temporaries, R31 address scratch.
Flags: F0 SHAKE family, F1 SHA-512 for H, T_l and H_msg (SHA2 with n > 16), F7 result."""
from htp_isa import *
import slh_ref as S

# table fields of TAB_SLH
(F_N, F_HP, F_D, F_A, F_K, F_LEN, F_M, F_L1, F_L2, F_L3, F_TREEMASK, F_LEAFMASK, F_SHAKE, F_BIG, F_HLEN, F_PADF, F_PADH,
 F_AMASK) = range(1, 19)

# RAM map
A_SEED, A_ROOT, A_R, A_DIG, A_INNER, A_NODE, A_AUTH, A_PAIR, A_TMP, A_WOTS, A_FROOTS = (
    0x000, 0x040, 0x080, 0x0C0, 0x100, 0x140, 0x180, 0x1C0, 0x200, 0x240, 0xB00)
RAM_NEED = 0xB00 + 35 * 32

rN, rHP, rD, rA, rK, rLEN, rM, rHLEN, rPADF, rPADH = range(10)
rLAY, rTRE, rTYP, rKP, rCH, rHS = range(10, 16)
rARG1, rARG2, rARG3, rSIG, rIT, rIL = 16, 17, 18, 19, 20, 21
rSC = 31

SLH_FIELDS = [('N', F_N), ('HP', F_HP), ('D', F_D), ('A', F_A), ('K', F_K), ('LEN', F_LEN), ('M', F_M)]


def slh_table():
    """TAB_SLH entries: key set number -> {field: value}."""
    t = {}
    for i, p in enumerate(S.SETS):
        n, hp, h, d = p['n'], p['hp'], p['h'], p['d']
        shake = int(p['fam'] == 'SHAKE')
        big = int((not shake) and n > 16)
        l1 = (p['k'] * p['a'] + 7) // 8
        l2 = (h - hp + 7) // 8
        l3 = (hp + 7) // 8
        t[(TAB_SLH, i)] = {F_N: n, F_HP: hp, F_D: d, F_A: p['a'], F_K: p['k'], F_LEN: p['len'], F_M: p['m'], F_L1: l1, F_L2: l2,
                           F_L3: l3, F_TREEMASK: (1 << (h - hp)) - 1, F_LEAFMASK: (1 << hp) - 1, F_SHAKE: shake, F_BIG: big,
                           F_HLEN: 64 if big else 32, F_PADF: 64 - n, F_PADH: (128 - n) if big else (64 - n),
                           F_AMASK: (1 << p['a']) - 1}
    return t


def emit_slh(a):
    """Emits the SLH-DSA program into the assembler a; entry label SLH_START; failure label SLH_FAIL."""
    E = a.emit
    L = a.label

    def ldt(rd, field, key=22):
        E('LDT', rd, key, 0, (TAB_SLH << 8) | field)

    def hram_c(addr, lenreg):
        E('LDI', rSC, 0, 0, addr)
        E('HRAM', 0, rSC, lenreg)

    def cpbr_to(addr, offreg, lenreg, area):
        E('LDI', rSC, 0, 0, addr)
        E('CPBR', rSC, offreg, lenreg, area)

    L('SLH_START')
    E('LDS', 22, 0, 0, S_FORM)
    E('ISZ', 2, 22)
    E('BRN', 0, 2, 0, target='SLH_OPUNS')
    E('LDS', 22, 0, 0, S_SLH)
    for name, f in (('N', F_N), ('HP', F_HP), ('D', F_D), ('A', F_A), ('K', F_K), ('LEN', F_LEN), ('M', F_M), ('HLEN', F_HLEN),
                    ('PADF', F_PADF), ('PADH', F_PADH)):
        ldt({'N': rN, 'HP': rHP, 'D': rD, 'A': rA, 'K': rK, 'LEN': rLEN, 'M': rM, 'HLEN': rHLEN, 'PADF': rPADF, 'PADH': rPADH}[name], f)
    ldt(23, F_SHAKE)
    E('EQI', 0, 23, 0, 1)
    ldt(23, F_BIG)
    E('EQI', 1, 23, 0, 1)
    E('ISZ', 2, rN)
    E('BRF', 0, 2, 0, target='SLH_FAIL')
    # public key and R into the RAM
    E('LDI', 23, 0, 0, 0)
    cpbr_to(A_SEED, 23, rN, AREA_PK)
    cpbr_to(A_ROOT, rN, rN, AREA_PK)
    cpbr_to(A_R, 23, rN, AREA_SIG)
    # H_msg
    E('CALL', imm=0, target='SLH_HMSG')
    # idx_tree and idx_leaf from the digest
    E('LDS', 22, 0, 0, S_SLH)
    ldt(25, F_L1)
    ldt(26, F_L2)
    ldt(28, F_L3)
    E('ADDI', 25, 25, 0, A_DIG)
    E('CALL', imm=0, target='SLH_B2I')              # R25 ptr, R26 count -> R27
    ldt(23, F_TREEMASK)
    E('AND', rIT, 27, 23)
    E('ADD', 25, 25, 26)
    E('MOV', 26, 28)
    E('CALL', imm=0, target='SLH_B2I')
    ldt(23, F_LEAFMASK)
    E('AND', rIL, 27, 23)
    # FORS
    E('LDI', rLAY, 0, 0, 0)
    E('MOV', rTRE, rIT)
    E('LDI', rTYP, 0, 0, 3)
    E('MOV', rKP, rIL)
    E('LDI', rCH, 0, 0, 0)
    E('LDI', rHS, 0, 0, 0)
    E('MOV', rSIG, rN)
    E('LDI', 22, 0, 0, 0)
    L('SLH_FLOOP')
    E('MUL', 23, 22, rA)
    E('SHRI', 24, 23, 0, 3)
    E('ANDI', 25, 23, 0, 7)
    E('ADDI', 24, 24, 0, A_DIG)
    E('RLB', 26, 24, 0, 0)
    E('RLB', 27, 24, 0, 1)
    E('RLB', 28, 24, 0, 2)
    E('SHLI', 26, 26, 0, 16)
    E('SHLI', 27, 27, 0, 8)
    E('OR', 26, 26, 27)
    E('OR', 26, 26, 28)
    E('ADD', 25, 25, rA)
    E('LDI', 27, 0, 0, 24)
    E('SUB', 27, 27, 25)
    E('SHR', 26, 26, 27)
    E('LDS', 29, 0, 0, S_SLH)
    E('LDT', 27, 29, 0, (TAB_SLH << 8) | F_AMASK)
    E('AND', 26, 26, 27)                           # idx of this tree
    E('SHL', 27, 22, rA)
    E('ADD', rHS, 27, 26)
    E('LDI', rCH, 0, 0, 0)
    cpbr_to(A_NODE, rSIG, rN, AREA_SIG)
    E('LDI', rARG1, 0, 0, A_NODE)
    E('LDI', rARG2, 0, 0, A_NODE)
    E('CALL', imm=0, target='SLH_HASHF')
    E('ADD', rSIG, rSIG, rN)
    E('LDI', 23, 0, 0, 0)
    L('SLH_AUTHL')
    E('ADDI', rCH, 23, 0, 1)
    cpbr_to(A_AUTH, rSIG, rN, AREA_SIG)
    E('ADD', rSIG, rSIG, rN)
    E('SHR', 27, 26, 23)
    E('ANDI', 27, 27, 0, 1)
    E('EQI', 2, 27, 0, 1)
    E('CALL', imm=0, target='SLH_PAIR')
    E('SHRI', rHS, rHS, 0, 1)
    E('LDI', rARG1, 0, 0, A_PAIR)
    E('LDI', rARG2, 0, 0, A_NODE)
    E('ADD', rARG3, rN, rN)
    E('CALL', imm=0, target='SLH_HASHH')
    E('ADDI', 23, 23, 0, 1)
    E('LTU', 3, 23, rA)
    E('BRF', 0, 3, 0, target='SLH_AUTHL')
    E('MUL', 28, 22, rN)
    E('ADDI', 28, 28, 0, A_FROOTS)
    E('LDI', 29, 0, 0, A_NODE)
    E('CPRR', 28, 29, rN)
    E('ADDI', 22, 22, 0, 1)
    E('LTU', 3, 22, rK)
    E('BRF', 0, 3, 0, target='SLH_FLOOP')
    E('LDI', rTYP, 0, 0, 4)
    E('LDI', rCH, 0, 0, 0)
    E('LDI', rHS, 0, 0, 0)
    E('LDI', rARG1, 0, 0, A_FROOTS)
    E('LDI', rARG2, 0, 0, A_NODE)
    E('MUL', rARG3, rK, rN)
    E('CALL', imm=0, target='SLH_HASHH')
    # hypertree
    E('LDI', 22, 0, 0, 0)
    L('SLH_HTL')
    E('MOV', rLAY, 22)
    E('MOV', rTRE, rIT)
    E('LDI', rTYP, 0, 0, 0)
    E('MOV', rKP, rIL)
    E('LDI', rCH, 0, 0, 0)
    E('LDI', rHS, 0, 0, 0)
    E('LDI', 23, 0, 0, 0)                           # csum
    E('LDI', 24, 0, 0, 0)
    E('ADD', 25, rN, rN)                            # 2n digits of the message
    L('SLH_CSL')
    E('CALL', imm=0, target='SLH_NIB')
    E('LDI', 28, 0, 0, 15)
    E('SUB', 28, 28, 27)
    E('ADD', 23, 23, 28)
    E('ADDI', 24, 24, 0, 1)
    E('LTU', 3, 24, 25)
    E('BRF', 0, 3, 0, target='SLH_CSL')
    E('SHLI', 23, 23, 0, 4)
    E('LDI', 24, 0, 0, 0)
    L('SLH_CHL')
    E('CALL', imm=0, target='SLH_NIB')              # R27 digit of index R24
    E('MOV', rCH, 24)
    E('MUL', 26, 24, rN)
    E('ADD', 28, rSIG, 26)
    cpbr_to(A_TMP, 28, rN, AREA_SIG)
    E('MOV', 26, 27)
    E('LDI', 28, 0, 0, 15)
    L('SLH_CHJ')
    E('LTU', 3, 26, 28)
    E('BRN', 0, 3, 0, target='SLH_CHD')
    E('MOV', rHS, 26)
    E('LDI', rARG1, 0, 0, A_TMP)
    E('LDI', rARG2, 0, 0, A_TMP)
    E('CALL', imm=0, target='SLH_HASHF')
    E('ADDI', 26, 26, 0, 1)
    E('JMP', imm=0, target='SLH_CHJ')
    L('SLH_CHD')
    E('MUL', 26, 24, rN)
    E('ADDI', 26, 26, 0, A_WOTS)
    E('LDI', 29, 0, 0, A_TMP)
    E('CPRR', 26, 29, rN)
    E('ADDI', 24, 24, 0, 1)
    E('LTU', 3, 24, rLEN)
    E('BRF', 0, 3, 0, target='SLH_CHL')
    E('LDI', rTYP, 0, 0, 1)
    E('LDI', rCH, 0, 0, 0)
    E('LDI', rHS, 0, 0, 0)
    E('LDI', rARG1, 0, 0, A_WOTS)
    E('LDI', rARG2, 0, 0, A_NODE)
    E('MUL', rARG3, rLEN, rN)
    E('CALL', imm=0, target='SLH_HASHH')
    E('LDI', rTYP, 0, 0, 2)
    E('LDI', rKP, 0, 0, 0)
    E('LDI', rCH, 0, 0, 0)
    E('MOV', rHS, rIL)
    E('LDI', 24, 0, 0, 0)
    L('SLH_CLL')
    E('ADDI', rCH, 24, 0, 1)
    E('MUL', 26, rLEN, rN)
    E('MUL', 27, 24, rN)
    E('ADD', 26, 26, 27)
    E('ADD', 26, 26, rSIG)
    cpbr_to(A_AUTH, 26, rN, AREA_SIG)
    E('SHR', 27, rIL, 24)
    E('ANDI', 27, 27, 0, 1)
    E('EQI', 2, 27, 0, 1)
    E('CALL', imm=0, target='SLH_PAIR')
    E('SHRI', rHS, rHS, 0, 1)
    E('LDI', rARG1, 0, 0, A_PAIR)
    E('LDI', rARG2, 0, 0, A_NODE)
    E('ADD', rARG3, rN, rN)
    E('CALL', imm=0, target='SLH_HASHH')
    E('ADDI', 24, 24, 0, 1)
    E('LTU', 3, 24, rHP)
    E('BRF', 0, 3, 0, target='SLH_CLL')
    # next layer
    E('LDS', 26, 0, 0, S_SLH)
    E('LDT', 26, 26, 0, (TAB_SLH << 8) | F_LEAFMASK)
    E('AND', rIL, rIT, 26)
    E('SHR', rIT, rIT, rHP)
    E('ADD', 26, rHP, rLEN)
    E('MUL', 26, 26, rN)
    E('ADD', rSIG, rSIG, 26)
    E('ADDI', 22, 22, 0, 1)
    E('LTU', 3, 22, rD)
    E('BRF', 0, 3, 0, target='SLH_HTL')
    E('LDI', 28, 0, 0, A_ROOT)
    E('LDI', 29, 0, 0, A_NODE)
    E('CMPRR', 7, 28, 29, rN)
    E('END')
    L('SLH_OPUNS')
    E('ERR', imm=1)
    L('SLH_FAIL')
    E('FSET', 7, 0, 0, 0)
    E('END')

    # ---- subroutines ----
    # B2I: R25 pointer into the RAM, R26 byte count -> R27 big-endian value
    L('SLH_B2I')
    E('LDI', 27, 0, 0, 0)
    E('MOV', 29, 25)
    E('MOV', 30, 26)
    L('SLH_B2I_L')
    E('ISZ', 3, 30)
    E('BRF', 0, 3, 0, target='SLH_B2I_E')
    E('SHLI', 27, 27, 0, 8)
    E('RLB', 24, 29, 0, 0)
    E('OR', 27, 27, 24)
    E('ADDI', 29, 29, 0, 1)
    E('SUBI', 30, 30, 0, 1)
    E('JMP', imm=0, target='SLH_B2I_L')
    L('SLH_B2I_E')
    E('RET')
    # NIB: R24 digit index, R25 = 2n, R23 csum -> R27 digit (message nibbles, then the checksum nibbles)
    L('SLH_NIB')
    E('LTU', 2, 24, 25)
    E('BRN', 0, 2, 0, target='SLH_NIB_CS')
    E('SHRI', 26, 24, 0, 1)
    E('ADDI', 26, 26, 0, A_NODE)
    E('RLB', 27, 26, 0, 0)
    E('ANDI', 28, 24, 0, 1)
    E('EQI', 2, 28, 0, 0)
    E('BRF', 0, 2, 0, target='SLH_NIB_HI')
    E('ANDI', 27, 27, 0, 15)
    E('RET')
    L('SLH_NIB_HI')
    E('SHRI', 27, 27, 0, 4)
    E('RET')
    L('SLH_NIB_CS')
    E('SUB', 26, 24, 25)
    E('SHLI', 26, 26, 0, 2)
    E('LDI', 28, 0, 0, 12)
    E('SUB', 28, 28, 26)
    E('SHR', 27, 23, 28)
    E('ANDI', 27, 27, 0, 15)
    E('RET')
    # PAIR: flag F2 set: pair = auth || node, otherwise node || auth, at A_PAIR
    L('SLH_PAIR')
    E('LDI', 28, 0, 0, A_PAIR)
    E('LDI', 29, 0, 0, A_NODE)
    E('LDI', 30, 0, 0, A_AUTH)
    E('ADD', 25, 28, rN)
    E('BRF', 0, 2, 0, target='SLH_PAIR_ODD')
    E('CPRR', 28, 29, rN)
    E('CPRR', 25, 30, rN)
    E('RET')
    L('SLH_PAIR_ODD')
    E('CPRR', 28, 30, rN)
    E('CPRR', 25, 29, rN)
    E('RET')
    # ADRSPUT: appends the address (compressed for SHA2)
    L('SLH_ADRS')
    E('BRF', 0, 0, 0, target='SLH_ADRS_SHAKE')
    E('HREG', 0, rLAY, 0, 1)
    E('HREG', 0, rTRE, 0, 8)
    E('HREG', 0, rTYP, 0, 1)
    E('HREG', 0, rKP, 0, 4)
    E('HREG', 0, rCH, 0, 4)
    E('HREG', 0, rHS, 0, 4)
    E('RET')
    L('SLH_ADRS_SHAKE')
    E('HREG', 0, rLAY, 0, 4)
    E('HZERI', imm=4)
    E('HREG', 0, rTRE, 0, 8)
    E('HREG', 0, rTYP, 0, 4)
    E('HREG', 0, rKP, 0, 4)
    E('HREG', 0, rCH, 0, 4)
    E('HREG', 0, rHS, 0, 4)
    E('RET')
    # HASHF: R16 address of M1 (n bytes), R17 destination
    L('SLH_HASHF')
    E('HCLR')
    hram_c(A_SEED, rN)
    E('BRF', 0, 0, 0, target='SLH_HF_NP')
    E('HZERO', 0, rPADF)
    L('SLH_HF_NP')
    E('CALL', imm=0, target='SLH_ADRS')
    E('HRAM', 0, rARG1, rN)
    E('BRF', 0, 0, 0, target='SLH_HF_SK')
    E('HGO', 0, 0, 0, H_SHA256)
    E('JMP', imm=0, target='SLH_HF_E')
    L('SLH_HF_SK')
    E('HGO', 0, rN, 0, H_SHAKE256)
    L('SLH_HF_E')
    E('DST', 0, rARG2, rN)
    E('RET')
    # HASHH: R16 address of the tail, R18 its length, R17 destination (H and T_l)
    L('SLH_HASHH')
    E('HCLR')
    hram_c(A_SEED, rN)
    E('BRF', 0, 0, 0, target='SLH_HH_NP')
    E('HZERO', 0, rPADH)
    L('SLH_HH_NP')
    E('CALL', imm=0, target='SLH_ADRS')
    E('HT1', 0, rARG1, rARG3, 0)
    E('BRF', 0, 0, 0, target='SLH_HH_SK')
    E('BRF', 0, 1, 0, target='SLH_HH_5')
    E('HGO', 0, 0, 0, H_SHA256)
    E('JMP', imm=0, target='SLH_HH_E')
    L('SLH_HH_5')
    E('HGO', 0, 0, 0, H_SHA512)
    E('JMP', imm=0, target='SLH_HH_E')
    L('SLH_HH_SK')
    E('HGO', 0, rN, 0, H_SHAKE256)
    L('SLH_HH_E')
    E('DST', 0, rARG2, rN)
    E('RET')
    # MPRE + HMSG: message-hash input and digest (pure form: 0x00 || len(ctx) || ctx || M)
    L('SLH_MPRE')
    E('LDI', 22, 0, 0, 0)
    E('HREG', 0, 22, 0, 1)
    E('LDS', 22, 0, 0, S_LEN_CTX)
    E('HREG', 0, 22, 0, 1)
    E('LDS', 23, 0, 0, S_LEN_MSG)
    E('LDS', 24, 0, 0, S_LEN_CTX)
    E('HT1', 0, 23, 24, 1 | (AREA_MSG << 1))
    E('LDI', 25, 0, 0, 0)
    E('LDS', 26, 0, 0, S_LEN_MSG)
    E('HT2', 0, 25, 26, 1 | (AREA_MSG << 1))
    E('RET')
    L('SLH_HMSG')
    E('HCLR')
    hram_c(A_R, rN)
    hram_c(A_SEED, rN)
    E('BRF', 0, 0, 0, target='SLH_HM_SK')
    # SHA2: inner hash, then MGF1
    hram_c(A_ROOT, rN)
    E('CALL', imm=0, target='SLH_MPRE')
    E('BRF', 0, 1, 0, target='SLH_HM_5')
    E('HGO', 0, 0, 0, H_SHA256)
    E('JMP', imm=0, target='SLH_HM_D')
    L('SLH_HM_5')
    E('HGO', 0, 0, 0, H_SHA512)
    L('SLH_HM_D')
    E('LDI', 22, 0, 0, A_INNER)
    E('DST', 0, 22, rHLEN)
    E('LDI', 22, 0, 0, 0)                           # counter
    E('LDI', 23, 0, 0, A_DIG)
    E('MOV', 24, rM)
    L('SLH_MGF')
    E('HCLR')
    hram_c(A_R, rN)
    hram_c(A_SEED, rN)
    hram_c(A_INNER, rHLEN)
    E('HREG', 0, 22, 0, 4)
    E('BRF', 0, 1, 0, target='SLH_MGF_5')
    E('HGO', 0, 0, 0, H_SHA256)
    E('JMP', imm=0, target='SLH_MGF_D')
    L('SLH_MGF_5')
    E('HGO', 0, 0, 0, H_SHA512)
    L('SLH_MGF_D')
    E('MOV', 25, rHLEN)
    E('LTU', 3, 24, rHLEN)
    E('BRN', 0, 3, 0, target='SLH_MGF_S')
    E('MOV', 25, 24)
    L('SLH_MGF_S')
    E('DST', 0, 23, 25)
    E('ADD', 23, 23, 25)
    E('SUB', 24, 24, 25)
    E('ADDI', 22, 22, 0, 1)
    E('ISZ', 3, 24)
    E('BRN', 0, 3, 0, target='SLH_MGF')
    E('RET')
    L('SLH_HM_SK')
    hram_c(A_ROOT, rN)
    E('CALL', imm=0, target='SLH_MPRE')
    E('HGO', 0, rM, 0, H_SHAKE256)
    E('LDI', 22, 0, 0, A_DIG)
    E('DST', 0, 22, rM)
    E('RET')
