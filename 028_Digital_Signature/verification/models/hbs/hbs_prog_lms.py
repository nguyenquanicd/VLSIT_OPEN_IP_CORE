"""LMS / HSS verification (RFC 8554 algorithms 4b, 6 and the HSS signature of section 6) as a program of the hash-tree
processor. The public key in the buffer is the HSS form u32 L || LMS public key (ASM-021, L = 1 for a plain LMS key) and
the signature is the HSS form u32 Nspk || (LMS signature || LMS public key)* || LMS signature. All levels use the
parameter set selected in dsig_set (homogeneous HSS).
Register map: R0 n, R1 h, R2 w, R3 p, R4 ls, R5 u, R6 largest digit 2^w-1, R7 2n, R8 level, R9 Nspk, R10 signature pointer,
R11 q, R12 node number, R13 expected LM-OTS code, R14 expected LMS code, R15 signature size of one level,
R17 hash destination, R19 message offset, R20 message length, R22..R28 temporaries, R30 constant 16, R31 address scratch.
Flags: F0 SHAKE, F3 last level (message from the message area), F7 result."""
from htp_isa import *
import lms_ref as L

# fields of TAB_LMS (key lmstype) and TAB_OTS (key lmots)
LF_N, LF_H, LF_SHAKE, LF_ID = 1, 2, 3, 4
OF_N, OF_W, OF_P, OF_LS, OF_U, OF_SHAKE, OF_ID, OF_MAX = 1, 2, 3, 4, 5, 6, 7, 8

A_I, A_K, A_Q, A_TMP, A_KC, A_NODE, A_AUTH, A_PAIR, A_Z = 0x000, 0x020, 0x040, 0x080, 0x0C0, 0x100, 0x140, 0x180, 0x200
RAM_NEED = 0x200 + 265 * 32

rN, rH, rW, rP, rLS, rU, rMAX, r2N, rLEV, rNSPK, rRS, rQ, rNODE, rOTS, rLMS, rSZ = range(16)
rDST, rMOFF, rMLEN = 17, 19, 20
r16 = 30


def lms_tables():
    t = {}
    for i in range(20):
        lp = L.lms_params(i)
        t[(TAB_LMS, i)] = {LF_N: lp['n'], LF_H: lp['h'], LF_SHAKE: int(lp['shake']), LF_ID: lp['code']}
    for i in range(16):
        op = L.ots_params(i)
        t[(TAB_OTS, i)] = {OF_N: op['n'], OF_W: op['w'], OF_P: op['p'], OF_LS: op['ls'], OF_U: op['u'], OF_SHAKE: int(op['shake']),
                           OF_ID: op['code'], OF_MAX: (1 << op['w']) - 1}
    return t


def emit_lms(a):
    E = a.emit
    Lb = a.label

    def hram_c(addr, lenreg):
        E('LDI', 31, 0, 0, addr)
        E('HRAM', 0, 31, lenreg)

    def cpbr_to(addr, offreg, lenreg, area):
        E('LDI', 31, 0, 0, addr)
        E('CPBR', 31, offreg, lenreg, area)

    def hreg_const(val, nbytes):
        E('LDI', 28, 0, 0, val)
        E('HREG', 0, 28, 0, nbytes)

    Lb('LMS_START')
    E('LDS', 22, 0, 0, S_LMSTYPE)
    E('LDS', 23, 0, 0, S_LMOTS)
    E('LDT', 24, 22, 0, (TAB_LMS << 8) | LF_N)
    E('LDT', rH, 22, 0, (TAB_LMS << 8) | LF_H)
    E('LDT', 25, 22, 0, (TAB_LMS << 8) | LF_SHAKE)
    E('LDT', rLMS, 22, 0, (TAB_LMS << 8) | LF_ID)
    E('LDT', rN, 23, 0, (TAB_OTS << 8) | OF_N)
    E('LDT', rW, 23, 0, (TAB_OTS << 8) | OF_W)
    E('LDT', rP, 23, 0, (TAB_OTS << 8) | OF_P)
    E('LDT', rLS, 23, 0, (TAB_OTS << 8) | OF_LS)
    E('LDT', rU, 23, 0, (TAB_OTS << 8) | OF_U)
    E('LDT', 26, 23, 0, (TAB_OTS << 8) | OF_SHAKE)
    E('LDT', rOTS, 23, 0, (TAB_OTS << 8) | OF_ID)
    E('LDT', rMAX, 23, 0, (TAB_OTS << 8) | OF_MAX)
    E('ISZ', 2, rN)
    E('BRF', 0, 2, 0, target='LMS_FAIL')
    E('EQ', 2, rN, 24)
    E('BRN', 0, 2, 0, target='LMS_FAIL')
    E('EQ', 2, 25, 26)
    E('BRN', 0, 2, 0, target='LMS_FAIL')
    E('EQI', 0, 25, 0, 1)
    E('ADD', r2N, rN, rN)
    E('LDI', r16, 0, 0, 16)
    # size of one LMS signature: 12 + (1 + p + h) n
    E('ADD', rSZ, rP, rH)
    E('ADDI', rSZ, rSZ, 0, 1)
    E('MUL', rSZ, rSZ, rN)
    E('ADDI', rSZ, rSZ, 0, 12)
    # HSS public key: L, level check against dsig_set.hsslvl
    E('LDI', 29, 0, 0, 0)
    E('CALL', imm=0, target='LMS_GET32_PK')
    E('MOV', 22, 27)
    E('LDS', 23, 0, 0, S_HSSLVL)
    E('EQ', 2, 22, 23)
    E('BRN', 0, 2, 0, target='LMS_FAIL')
    E('ISZ', 2, 22)
    E('BRF', 0, 2, 0, target='LMS_FAIL')
    E('SUBI', rNSPK, 22, 0, 1)
    # key of level 0: type codes, I and T1 from the public key
    E('LDI', 29, 0, 0, 4)
    E('CALL', imm=0, target='LMS_GET32_PK')
    E('EQ', 2, 27, rLMS)
    E('BRN', 0, 2, 0, target='LMS_FAIL')
    E('LDI', 29, 0, 0, 8)
    E('CALL', imm=0, target='LMS_GET32_PK')
    E('EQ', 2, 27, rOTS)
    E('BRN', 0, 2, 0, target='LMS_FAIL')
    E('LDI', 29, 0, 0, 12)
    cpbr_to(A_I, 29, r16, AREA_PK)
    E('LDI', 29, 0, 0, 28)
    cpbr_to(A_K, 29, rN, AREA_PK)
    # Nspk of the signature
    E('LDI', 29, 0, 0, 0)
    E('CALL', imm=0, target='LMS_GET32_SIG')
    E('EQ', 2, 27, rNSPK)
    E('BRN', 0, 2, 0, target='LMS_FAIL')
    E('LDI', rRS, 0, 0, 4)
    E('LDI', rLEV, 0, 0, 0)
    Lb('LMS_LVL')
    E('EQ', 3, rLEV, rNSPK)                       # F3: last level
    E('BRF', 0, 3, 0, target='LMS_LAST')
    E('ADD', rMOFF, rRS, rSZ)                     # message: the next public key in the signature
    E('ADDI', rMLEN, rN, 0, 24)
    E('CALL', imm=0, target='LMS_ONE')
    E('BRN', 0, 7, 0, target='LMS_FAIL')
    # next key: type codes, I and T1
    E('MOV', 29, rMOFF)
    E('CALL', imm=0, target='LMS_GET32_SIG')
    E('EQ', 2, 27, rLMS)
    E('BRN', 0, 2, 0, target='LMS_FAIL')
    E('ADDI', 29, rMOFF, 0, 4)
    E('CALL', imm=0, target='LMS_GET32_SIG')
    E('EQ', 2, 27, rOTS)
    E('BRN', 0, 2, 0, target='LMS_FAIL')
    E('ADDI', 29, rMOFF, 0, 8)
    cpbr_to(A_I, 29, r16, AREA_SIG)
    E('ADDI', 29, rMOFF, 0, 24)
    cpbr_to(A_K, 29, rN, AREA_SIG)
    E('MOV', rRS, rMOFF)
    E('ADDI', rRS, rRS, 0, 24)
    E('ADD', rRS, rRS, rN)
    E('ADDI', rLEV, rLEV, 0, 1)
    E('JMP', imm=0, target='LMS_LVL')
    Lb('LMS_LAST')
    E('LDI', rMOFF, 0, 0, 0)
    E('LDS', rMLEN, 0, 0, S_LEN_MSG)
    E('CALL', imm=0, target='LMS_ONE')
    E('END')
    Lb('LMS_FAIL')
    E('FSET', 7, 0, 0, 0)
    E('END')

    # GET32_SIG / GET32_PK: R29 byte offset -> R27 big-endian 32-bit value
    for nm, area in (('LMS_GET32_SIG', AREA_SIG), ('LMS_GET32_PK', AREA_PK)):
        Lb(nm)
        E('BLB', 27, 29, 0, area | (0 << 2))
        for k in (1, 2, 3):
            E('BLB', 28, 29, 0, area | (k << 2))
            E('SHLI', 27, 27, 0, 8)
            E('OR', 27, 27, 28)
        E('RET')

    # COEF: R23 index i -> R27 coefficient i of Q || cksm (RAM A_Q)
    Lb('LMS_COEF')
    E('MUL', 24, 23, rW)
    E('SHRI', 25, 24, 0, 3)
    E('ADDI', 25, 25, 0, A_Q)
    E('RLB', 26, 25, 0, 0)
    E('ANDI', 24, 24, 0, 7)
    E('ADD', 24, 24, rW)
    E('LDI', 25, 0, 0, 8)
    E('SUB', 25, 25, 24)
    E('SHR', 26, 26, 25)
    E('AND', 27, 26, rMAX)
    E('RET')

    # LHG: runs the hash of the family and stores n bytes at R17
    Lb('LMS_LHG')
    E('BRF', 0, 0, 0, target='LMS_LHG_SK')
    E('HGO', 0, 0, 0, H_SHA256)
    E('JMP', imm=0, target='LMS_LHG_E')
    Lb('LMS_LHG_SK')
    E('HGO', 0, rN, 0, H_SHAKE256)
    Lb('LMS_LHG_E')
    E('DST', 0, rDST, rN)
    E('RET')

    # ONE: verifies the LMS signature at SIG offset R10 with the key in the RAM; the message is the
    # SIG area (F3 = 0) or the MSG area (F3 = 1) at R19, R20 bytes; result in F7
    Lb('LMS_ONE')
    E('MOV', 29, rRS)
    E('CALL', imm=0, target='LMS_GET32_SIG')
    E('MOV', rQ, 27)
    E('LDI', 22, 0, 0, 1)
    E('SHL', 22, 22, rH)
    E('LTU', 2, rQ, 22)
    E('BRN', 0, 2, 0, target='LMS_ONE_F')
    E('ADDI', 29, rRS, 0, 4)
    E('CALL', imm=0, target='LMS_GET32_SIG')
    E('EQ', 2, 27, rOTS)
    E('BRN', 0, 2, 0, target='LMS_ONE_F')
    E('MUL', 22, rP, rN)
    E('ADD', 22, 22, rN)
    E('ADD', 29, rRS, 22)
    E('ADDI', 29, 29, 0, 8)
    E('CALL', imm=0, target='LMS_GET32_SIG')
    E('EQ', 2, 27, rLMS)
    E('BRN', 0, 2, 0, target='LMS_ONE_F')
    # Q = H(I || q || D_MESG || C || message)
    E('HCLR')
    hram_c(A_I, r16)
    E('HREG', 0, rQ, 0, 4)
    hreg_const(L.D_MESG, 2)
    E('ADDI', 29, rRS, 0, 8)
    E('HBUF', 0, 29, rN, AREA_SIG)
    E('BRF', 0, 3, 0, target='LMS_ONE_QM')
    E('HT1', 0, rMOFF, rMLEN, 1 | (AREA_SIG << 1))
    E('JMP', imm=0, target='LMS_ONE_QH')
    Lb('LMS_ONE_QM')
    E('HT1', 0, rMOFF, rMLEN, 1 | (AREA_MSG << 1))
    Lb('LMS_ONE_QH')
    E('LDI', rDST, 0, 0, A_Q)
    E('CALL', imm=0, target='LMS_LHG')
    # checksum of Q, two bytes after Q
    E('LDI', 21, 0, 0, 0)
    E('LDI', 23, 0, 0, 0)
    Lb('LMS_CK')
    E('CALL', imm=0, target='LMS_COEF')
    E('SUB', 28, rMAX, 27)
    E('ADD', 21, 21, 28)
    E('ADDI', 23, 23, 0, 1)
    E('LTU', 2, 23, rU)
    E('BRF', 0, 2, 0, target='LMS_CK')
    E('SHL', 21, 21, rLS)
    E('ANDI', 21, 21, 0, 0xFFFF)
    E('LDI', 22, 0, 0, A_Q)
    E('ADD', 22, 22, rN)
    E('SHRI', 25, 21, 0, 8)
    E('RSB', 0, 22, 25, 0)
    E('RSB', 0, 22, 21, 1)
    # chains
    E('LDI', 23, 0, 0, 0)
    Lb('LMS_ZL')
    E('CALL', imm=0, target='LMS_COEF')
    E('MUL', 22, 23, rN)
    E('ADD', 22, 22, rRS)
    E('ADD', 22, 22, rN)
    E('ADDI', 22, 22, 0, 8)
    cpbr_to(A_TMP, 22, rN, AREA_SIG)
    E('MOV', 26, 27)
    Lb('LMS_ZJ')
    E('LTU', 2, 26, rMAX)
    E('BRN', 0, 2, 0, target='LMS_ZD')
    E('HCLR')
    hram_c(A_I, r16)
    E('HREG', 0, rQ, 0, 4)
    E('HREG', 0, 23, 0, 2)
    E('HREG', 0, 26, 0, 1)
    hram_c(A_TMP, rN)
    E('LDI', rDST, 0, 0, A_TMP)
    E('CALL', imm=0, target='LMS_LHG')
    E('ADDI', 26, 26, 0, 1)
    E('JMP', imm=0, target='LMS_ZJ')
    Lb('LMS_ZD')
    E('MUL', 22, 23, rN)
    E('ADDI', 22, 22, 0, A_Z)
    E('LDI', 25, 0, 0, A_TMP)
    E('CPRR', 22, 25, rN)
    E('ADDI', 23, 23, 0, 1)
    E('LTU', 2, 23, rP)
    E('BRF', 0, 2, 0, target='LMS_ZL')
    # candidate public key of the one-time key
    E('HCLR')
    hram_c(A_I, r16)
    E('HREG', 0, rQ, 0, 4)
    hreg_const(L.D_PBLC, 2)
    E('MUL', 22, rP, rN)
    E('LDI', 25, 0, 0, A_Z)
    E('HT1', 0, 25, 22, 0)
    E('LDI', rDST, 0, 0, A_KC)
    E('CALL', imm=0, target='LMS_LHG')
    # leaf and path
    E('LDI', 22, 0, 0, 1)
    E('SHL', 22, 22, rH)
    E('ADD', rNODE, 22, rQ)
    E('HCLR')
    hram_c(A_I, r16)
    E('HREG', 0, rNODE, 0, 4)
    hreg_const(L.D_LEAF, 2)
    hram_c(A_KC, rN)
    E('LDI', rDST, 0, 0, A_NODE)
    E('CALL', imm=0, target='LMS_LHG')
    E('LDI', 23, 0, 0, 0)
    Lb('LMS_PL')
    E('MUL', 22, rP, rN)
    E('ADD', 22, 22, rN)
    E('ADD', 22, 22, rRS)
    E('ADDI', 22, 22, 0, 12)
    E('MUL', 24, 23, rN)
    E('ADD', 22, 22, 24)
    cpbr_to(A_AUTH, 22, rN, AREA_SIG)
    E('ANDI', 24, rNODE, 0, 1)
    E('EQI', 2, 24, 0, 1)
    E('SHRI', rNODE, rNODE, 0, 1)
    E('LDI', 25, 0, 0, A_PAIR)
    E('LDI', 26, 0, 0, A_NODE)
    E('LDI', 27, 0, 0, A_AUTH)
    E('ADD', 28, 25, rN)
    E('BRF', 0, 2, 0, target='LMS_PL_ODD')
    E('CPRR', 25, 26, rN)
    E('CPRR', 28, 27, rN)
    E('JMP', imm=0, target='LMS_PL_D')
    Lb('LMS_PL_ODD')
    E('CPRR', 25, 27, rN)
    E('CPRR', 28, 26, rN)
    Lb('LMS_PL_D')
    E('HCLR')
    hram_c(A_I, r16)
    E('HREG', 0, rNODE, 0, 4)
    hreg_const(L.D_INTR, 2)
    hram_c(A_PAIR, r2N)
    E('LDI', rDST, 0, 0, A_NODE)
    E('CALL', imm=0, target='LMS_LHG')
    E('ADDI', 23, 23, 0, 1)
    E('LTU', 2, 23, rH)
    E('BRF', 0, 2, 0, target='LMS_PL')
    E('LDI', 25, 0, 0, A_NODE)
    E('LDI', 26, 0, 0, A_K)
    E('CMPRR', 7, 25, 26, rN)
    E('RET')
    Lb('LMS_ONE_F')
    E('FSET', 7, 0, 0, 0)
    E('RET')
