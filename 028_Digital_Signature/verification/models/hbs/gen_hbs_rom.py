"""Generates rtl/m_vlsit_dsig_hbs_rom.sv: the program ROM, the constant tables and the entry addresses of the hash-based
verification engine, from the programs hbs_prog_slh.py, hbs_prog_lms.py and hbs_prog_xmss.py (tested by test_hbs_*.py).
Usage: python gen_hbs_rom.py <output .sv>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from htp_isa import *
import hbs_prog_slh as S
import hbs_prog_lms as LM
import hbs_prog_xmss as XM


def program():
    a = Asm()
    S.emit_slh(a)
    LM.emit_lms(a)
    XM.emit_xmss(a)
    return a


def encode(ins):
    op, rd, ra, rb, imm = ins
    assert 0 <= imm < (1 << 43), (op, imm)
    return (OPC[op] << 58) | (rd << 53) | (ra << 48) | (rb << 43) | imm


def main(path):
    a = program()
    code = a.resolve(0)
    words = [encode(i) for i in code]
    tabs = {}
    tabs.update(S.slh_table())
    tabs.update(LM.lms_tables())
    tabs.update(XM.xmss_tables())
    n = len(words)
    L = ['/*',
         ' * Generated by verification/models/hbs/gen_hbs_rom.py from hbs_prog_slh.py, hbs_prog_lms.py and hbs_prog_xmss.py;',
         ' * do not edit by hand. Program ROM, constant tables and entry addresses of the hash-based verification engine',
         ' * m_vlsit_dsig_hbs. %d instructions of 64 bits. Tables: 0 SLH-DSA (key: set), 1 LMS (key: type), 2 LM-OTS (key: type),' % n,
         ' * 3 XMSS (key: set). The type codes of the LMS and XMSS tables follow RFC 8554 and SP 800-208 (assumption ASM-022).',
         ' */',
         '`timescale 1ns/1ps', '',
         'module m_vlsit_dsig_hbs_rom (',
         '  input  wire  [11:0]  i_pc,',
         '  output logic [63:0]  o_ins,',
         '  input  wire  [1:0]   i_tab,',
         '  input  wire  [6:0]   i_key,',
         '  input  wire  [7:0]   i_field,',
         '  output logic [63:0]  o_val,',
         '  input  wire  [1:0]   i_which,',
         '  output logic [11:0]  o_entry',
         ');', '', '  // Program ROM', '  always_comb begin : p_com_rom', '    case (i_pc)']
    for i, w in enumerate(words):
        L.append("      12'd%d: o_ins = 64'h%016x;" % (i, w))
    L += ["      default: o_ins = 64'd0;", '    endcase', '  end', '',
          '  // Entry address: 0 SLH-DSA, 1 LMS and HSS, 2 XMSS and XMSS^MT', '  always_comb begin : p_com_entry', '    case (i_which)',
          "      2'd0: o_entry = 12'd%d;" % a.labels['SLH_START'],
          "      2'd1: o_entry = 12'd%d;" % a.labels['LMS_START'],
          "      2'd2: o_entry = 12'd%d;" % a.labels['XMSS_START'],
          "      default: o_entry = 12'd0;", '    endcase', '  end', '',
          '  // Constant tables', '  always_comb begin : p_com_tab', "    o_val = 64'd0;", '    case ({i_tab, i_key, i_field})']
    for (tab, key), fields in sorted(tabs.items()):
        for f, v in sorted(fields.items()):
            L.append("      {2'd%d, 7'd%d, 8'd%d}: o_val = 64'h%x;" % (tab, key, f, v))
    L += ["      default: o_val = 64'd0;", '    endcase', '  end', '', 'endmodule']
    open(path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'common'))
    import rom_postfix
    rom_postfix.finish(path)
    print('%d instructions, %d table entries' % (n, sum(len(f) for f in tabs.values())))
    assert n < 4096
    print({k: v for k, v in a.labels.items() if k.endswith('_START')})


if __name__ == '__main__':
    sys.exit(main(sys.argv[1]))
