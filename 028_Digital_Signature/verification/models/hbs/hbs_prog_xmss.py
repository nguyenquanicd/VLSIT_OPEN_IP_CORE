"""XMSS and XMSS^MT verification (RFC 8391 algorithms 13, 14 and 17 as I know them; hash functions, padding and type
codes of SP 800-208 section 5) as a program of the hash-tree processor.
Register map: R0 n, R1 len, R2 h' (height of one tree), R3 d (layers), R4 index bytes, R5 pl-1 (padding zeros), R6 2n,
R8 expected type code, R10..R16 address words (layer, tree, type, word 3, chain/height, hash/index, key and mask),
R17..R19 arguments (left, right, destination), R20 idx_leaf, R21 idx_tree, R22 signature pointer, R23 idx,
R24..R30 temporaries, R31 address scratch. Flag F0 SHAKE, F7 result."""
from htp_isa import *
import xmss_ref as X

XF_N, XF_LEN, XF_HP, XF_D, XF_IDXLEN, XF_PL1, XF_SHAKE, XF_OID, XF_HMASK = 1, 2, 3, 4, 5, 6, 7, 8, 9

A_SEED, A_ROOT, A_KEY, A_BM, A_BM1, A_X, A_TMP, A_AUTH, A_NODE, A_PAIR, A_WOTS = (
    0x000, 0x040, 0x080, 0x0C0, 0x100, 0x140, 0x180, 0x1C0, 0x200, 0x240, 0x300)
RAM_NEED = 0x300 + 67 * 32

rN, rLEN, rHP, rD, rIDXL, rPL1, r2N = 0, 1, 2, 3, 4, 5, 6
rOID = 8
rLAY, rTRE, rTYP, rW3, rW4, rW5, rKAM = range(10, 17)
rARGL, rARGR, rDEST = 17, 18, 19
rIL, rIT, rSIG, rIDX = 20, 21, 22, 23


def xmss_tables():
    t = {}
    for i, p in enumerate(X.SETS):
        t[(TAB_XMSS, i)] = {XF_N: p['n'], XF_LEN: p['len'], XF_HP: p['hp'], XF_D: p['d'], XF_IDXLEN: p['idxlen'],
                            XF_PL1: p['pl'] - 1, XF_SHAKE: int(p['fam'] == 'SHAKE256'), XF_OID: p['oid'],
                            XF_HMASK: (1 << p['hp']) - 1}
    return t


def emit_xmss(a):
    E = a.emit
    Lb = a.label

    def ldt(rd, field):
        E('LDT', rd, 24, 0, (TAB_XMSS << 8) | field)

    def hram_c(addr, lenreg):
        E('LDI', 31, 0, 0, addr)
        E('HRAM', 0, 31, lenreg)

    def cpbr_to(addr, offreg, lenreg, area):
        E('LDI', 31, 0, 0, addr)
        E('CPBR', 31, offreg, lenreg, area)

    def set_adrs(typ=None, w3=None, w4=None, w5=None, kam=None):
        for r, v in ((rTYP, typ), (rW3, w3), (rW4, w4), (rW5, w5), (rKAM, kam)):
            if v is not None:
                E('LDI', r, 0, 0, v)

    Lb('XMSS_START')
    E('LDS', 24, 0, 0, S_XMSS)
    ldt(rN, XF_N)
    ldt(rLEN, XF_LEN)
    ldt(rHP, XF_HP)
    ldt(rD, XF_D)
    ldt(rIDXL, XF_IDXLEN)
    ldt(rPL1, XF_PL1)
    ldt(rOID, XF_OID)
    ldt(25, XF_SHAKE)
    E('EQI', 0, 25, 0, 1)
    E('ISZ', 2, rN)
    E('BRF', 0, 2, 0, target='XMSS_FAIL')
    E('ADD', r2N, rN, rN)
    # public key: OID, root, seed
    E('LDI', 29, 0, 0, 0)
    E('CALL', imm=0, target='XMSS_GET32_PK')
    E('EQ', 2, 27, rOID)
    E('BRN', 0, 2, 0, target='XMSS_FAIL')
    E('LDI', 29, 0, 0, 4)
    cpbr_to(A_ROOT, 29, rN, AREA_PK)
    E('ADDI', 29, 29, 0, 0)
    E('ADD', 29, 29, rN)
    cpbr_to(A_SEED, 29, rN, AREA_PK)
    # idx from the signature
    E('LDI', rIDX, 0, 0, 0)
    E('LDI', 28, 0, 0, 0)
    Lb('XMSS_IDXL')
    E('SHLI', rIDX, rIDX, 0, 8)
    E('BLB', 27, 28, 0, AREA_SIG)
    E('OR', rIDX, rIDX, 27)
    E('ADDI', 28, 28, 0, 1)
    E('LTU', 2, 28, rIDXL)
    E('BRF', 0, 2, 0, target='XMSS_IDXL')
    # M' = H_msg(r || root || toByte(idx, n), M)
    E('HCLR')
    E('HZERO', 0, rPL1)
    E('LDI', 27, 0, 0, 2)
    E('HREG', 0, 27, 0, 1)
    E('MOV', 29, rIDXL)
    cpbr_to(A_X, 29, rN, AREA_SIG)             # r (n bytes from signature offset idxlen)
    hram_c(A_X, rN)
    hram_c(A_ROOT, rN)
    E('SUBI', 27, rN, 0, 8)
    E('HZERO', 0, 27)
    E('HREG', 0, rIDX, 0, 8)
    E('LDS', 27, 0, 0, S_LEN_MSG)
    E('LDI', 28, 0, 0, 0)
    E('HT1', 0, 28, 27, 1 | (AREA_MSG << 1))
    E('LDI', rDEST, 0, 0, A_NODE)
    E('CALL', imm=0, target='XMSS_HGO')
    # indexes of the first layer
    E('LDI', 24, 0, 0, 0)
    E('LDS', 24, 0, 0, S_XMSS)
    ldt(26, XF_HMASK)
    E('AND', rIL, rIDX, 26)
    E('SHR', rIT, rIDX, rHP)
    E('ADD', rSIG, rIDXL, rN)                  # first reduced signature
    E('LDI', 28, 0, 0, 0)                      # layer
    Lb('XMSS_LAYER')
    E('MOV', rLAY, 28)
    E('MOV', rTRE, rIT)
    # WOTS+ public key from the signature: digits of the node (2n message digits and 3 checksum digits)
    set_adrs(typ=0, w3=0, w4=0, w5=0, kam=0)
    E('MOV', rW3, rIL)
    E('LDI', 23, 0, 0, 0)                      # checksum
    E('LDI', 24, 0, 0, 0)
    Lb('XMSS_CSL')
    E('CALL', imm=0, target='XMSS_NIB')
    E('LDI', 26, 0, 0, 15)
    E('SUB', 26, 26, 27)
    E('ADD', 23, 23, 26)
    E('ADDI', 24, 24, 0, 1)
    E('LTU', 2, 24, r2N)
    E('BRF', 0, 2, 0, target='XMSS_CSL')
    E('SHLI', 23, 23, 0, 4)
    E('LDI', 24, 0, 0, 0)
    Lb('XMSS_CHL')
    E('CALL', imm=0, target='XMSS_NIB')        # R27 = digit of index R24
    E('MOV', rW4, 24)
    E('MUL', 26, 24, rN)
    E('ADD', 26, 26, rSIG)
    cpbr_to(A_TMP, 26, rN, AREA_SIG)
    E('MOV', 25, 27)                           # hash address, from the digit
    E('LDI', 26, 0, 0, 15)
    Lb('XMSS_CHJ')
    E('LTU', 2, 25, 26)
    E('BRN', 0, 2, 0, target='XMSS_CHD')
    E('MOV', rW5, 25)
    E('LDI', rKAM, 0, 0, 0)
    E('LDI', rDEST, 0, 0, A_KEY)
    E('CALL', imm=0, target='XMSS_PRF')
    E('LDI', rKAM, 0, 0, 1)
    E('LDI', rDEST, 0, 0, A_BM)
    E('CALL', imm=0, target='XMSS_PRF')
    E('LDI', 27, 0, 0, A_X)
    E('LDI', 28, 0, 0, A_TMP)
    E('LDI', 29, 0, 0, A_BM)
    E('XORR', 27, 28, 29, rN)
    E('LDI', rARGL, 0, 0, A_X)
    E('LDI', rDEST, 0, 0, A_TMP)
    E('CALL', imm=0, target='XMSS_F')
    E('ADDI', 25, 25, 0, 1)
    E('JMP', imm=0, target='XMSS_CHJ')
    Lb('XMSS_CHD')
    E('MUL', 26, 24, rN)
    E('ADDI', 26, 26, 0, A_WOTS)
    E('LDI', 29, 0, 0, A_TMP)
    E('CPRR', 26, 29, rN)
    E('ADDI', 24, 24, 0, 1)
    E('LTU', 2, 24, rLEN)
    E('BRF', 0, 2, 0, target='XMSS_CHL')
    # L-tree over the len nodes in A_WOTS
    set_adrs(typ=1, w4=0, w5=0, kam=0)
    E('MOV', 25, rLEN)                         # node count
    Lb('XMSS_LT')
    E('LDI', 24, 0, 0, 0)                      # i
    E('SHRI', 26, 25, 0, 1)                    # floor(count / 2)
    Lb('XMSS_LTI')
    E('LTU', 2, 24, 26)
    E('BRN', 0, 2, 0, target='XMSS_LTE')
    E('MOV', rW5, 24)
    E('SHLI', 27, 24, 0, 1)
    E('MUL', 28, 27, rN)
    E('ADDI', rARGL, 28, 0, A_WOTS)
    E('ADD', rARGR, rARGL, rN)
    E('MUL', 28, 24, rN)
    E('ADDI', rDEST, 28, 0, A_WOTS)
    E('CALL', imm=0, target='XMSS_RH')
    E('ADDI', 24, 24, 0, 1)
    E('JMP', imm=0, target='XMSS_LTI')
    Lb('XMSS_LTE')
    E('ANDI', 27, 25, 0, 1)
    E('EQI', 2, 27, 0, 1)
    E('BRN', 0, 2, 0, target='XMSS_LTN')
    E('SUBI', 27, 25, 0, 1)                    # odd: the last node moves to index floor(count/2)
    E('MUL', 27, 27, rN)
    E('ADDI', 27, 27, 0, A_WOTS)
    E('MUL', 28, 26, rN)
    E('ADDI', 28, 28, 0, A_WOTS)
    E('CPRR', 28, 27, rN)
    Lb('XMSS_LTN')
    E('ADDI', 25, 25, 0, 1)
    E('SHRI', 25, 25, 0, 1)                    # ceil(count / 2)
    E('ADDI', rW4, rW4, 0, 1)
    E('LDI', 27, 0, 0, 1)
    E('LTU', 2, 27, 25)
    E('BRF', 0, 2, 0, target='XMSS_LT')
    E('LDI', 27, 0, 0, A_WOTS)
    E('LDI', 28, 0, 0, A_NODE)
    E('CPRR', 28, 27, rN)
    # authentication path
    set_adrs(typ=2, w3=0, w4=0, w5=0, kam=0)
    E('MOV', rW5, rIL)
    E('LDI', 24, 0, 0, 0)
    Lb('XMSS_AUL')
    E('MOV', rW4, 24)
    E('MUL', 26, rLEN, rN)
    E('MUL', 27, 24, rN)
    E('ADD', 26, 26, 27)
    E('ADD', 26, 26, rSIG)
    cpbr_to(A_AUTH, 26, rN, AREA_SIG)
    E('SHR', 27, rIL, 24)
    E('ANDI', 27, 27, 0, 1)
    E('EQI', 2, 27, 0, 1)
    E('SHRI', rW5, rW5, 0, 1)
    E('BRF', 0, 2, 0, target='XMSS_AUO')
    E('LDI', rARGL, 0, 0, A_NODE)
    E('LDI', rARGR, 0, 0, A_AUTH)
    E('JMP', imm=0, target='XMSS_AUH')
    Lb('XMSS_AUO')
    E('LDI', rARGL, 0, 0, A_AUTH)
    E('LDI', rARGR, 0, 0, A_NODE)
    Lb('XMSS_AUH')
    E('LDI', rDEST, 0, 0, A_NODE)
    E('CALL', imm=0, target='XMSS_RH')
    E('ADDI', 24, 24, 0, 1)
    E('LTU', 2, 24, rHP)
    E('BRF', 0, 2, 0, target='XMSS_AUL')
    # next layer
    E('LDS', 24, 0, 0, S_XMSS)
    ldt(26, XF_HMASK)
    E('AND', rIL, rIT, 26)
    E('SHR', rIT, rIT, rHP)
    E('ADD', 26, rLEN, rHP)
    E('MUL', 26, 26, rN)
    E('ADD', rSIG, rSIG, 26)
    E('ADDI', 28, rLAY, 0, 1)
    E('LTU', 2, 28, rD)
    E('BRF', 0, 2, 0, target='XMSS_LAYER')
    E('LDI', 27, 0, 0, A_ROOT)
    E('LDI', 28, 0, 0, A_NODE)
    E('CMPRR', 7, 27, 28, rN)
    E('END')
    Lb('XMSS_FAIL')
    E('FSET', 7, 0, 0, 0)
    E('END')

    # GET32_PK: R29 byte offset -> R27 big-endian word
    Lb('XMSS_GET32_PK')
    E('BLB', 27, 29, 0, AREA_PK | (0 << 2))
    for k in (1, 2, 3):
        E('BLB', 28, 29, 0, AREA_PK | (k << 2))
        E('SHLI', 27, 27, 0, 8)
        E('OR', 27, 27, 28)
    E('RET')
    # NIB: R24 digit index, R2N = 2n -> R27 digit of the node in A_NODE (then the checksum digits of R23)
    Lb('XMSS_NIB')
    E('LTU', 2, 24, r2N)
    E('BRN', 0, 2, 0, target='XMSS_NIB_CS')
    E('SHRI', 26, 24, 0, 1)
    E('ADDI', 26, 26, 0, A_NODE)
    E('RLB', 27, 26, 0, 0)
    E('ANDI', 28, 24, 0, 1)
    E('EQI', 2, 28, 0, 0)
    E('BRF', 0, 2, 0, target='XMSS_NIB_HI')
    E('ANDI', 27, 27, 0, 15)
    E('RET')
    Lb('XMSS_NIB_HI')
    E('SHRI', 27, 27, 0, 4)
    E('RET')
    Lb('XMSS_NIB_CS')
    E('SUB', 26, 24, r2N)
    E('SHLI', 26, 26, 0, 2)
    E('LDI', 28, 0, 0, 12)
    E('SUB', 28, 28, 26)
    E('SHR', 27, 23, 28)
    E('ANDI', 27, 27, 0, 15)
    E('RET')
    # ADRS: appends the 32-byte address
    Lb('XMSS_ADRS')
    E('HREG', 0, rLAY, 0, 4)
    E('HREG', 0, rTRE, 0, 8)
    E('HREG', 0, rTYP, 0, 4)
    E('HREG', 0, rW3, 0, 4)
    E('HREG', 0, rW4, 0, 4)
    E('HREG', 0, rW5, 0, 4)
    E('HREG', 0, rKAM, 0, 4)
    E('RET')
    # HGO: family hash into R19
    Lb('XMSS_HGO')
    E('BRF', 0, 0, 0, target='XMSS_HGO_SK')
    E('HGO', 0, 0, 0, H_SHA256)
    E('JMP', imm=0, target='XMSS_HGO_E')
    Lb('XMSS_HGO_SK')
    E('HGO', 0, rN, 0, H_SHAKE256)
    Lb('XMSS_HGO_E')
    E('DST', 0, rDEST, rN)
    E('RET')
    # PRF(SEED, ADRS) -> R19
    Lb('XMSS_PRF')
    E('HCLR')
    E('HZERO', 0, rPL1)
    E('LDI', 27, 0, 0, 3)
    E('HREG', 0, 27, 0, 1)
    hram_c(A_SEED, rN)
    E('CALL', imm=0, target='XMSS_ADRS')
    E('CALL', imm=0, target='XMSS_HGO')
    E('RET')
    # F(KEY in A_KEY, M at R17) -> R19
    Lb('XMSS_F')
    E('HCLR')
    E('HZERO', 0, rPL1)
    E('LDI', 27, 0, 0, 0)
    E('HREG', 0, 27, 0, 1)
    hram_c(A_KEY, rN)
    E('HRAM', 0, rARGL, rN)
    E('CALL', imm=0, target='XMSS_HGO')
    E('RET')
    # RAND_HASH(left R17, right R18) -> R19
    Lb('XMSS_RH')
    E('LDI', rKAM, 0, 0, 0)
    E('MOV', 30, rDEST)
    E('LDI', rDEST, 0, 0, A_KEY)
    E('CALL', imm=0, target='XMSS_PRF')
    E('LDI', rKAM, 0, 0, 1)
    E('LDI', rDEST, 0, 0, A_BM)
    E('CALL', imm=0, target='XMSS_PRF')
    E('LDI', rKAM, 0, 0, 2)
    E('LDI', rDEST, 0, 0, A_BM1)
    E('CALL', imm=0, target='XMSS_PRF')
    E('LDI', 27, 0, 0, A_PAIR)
    E('LDI', 28, 0, 0, A_BM)
    E('XORR', 27, rARGL, 28, rN)
    E('ADD', 27, 27, rN)
    E('LDI', 28, 0, 0, A_BM1)
    E('XORR', 27, rARGR, 28, rN)
    E('HCLR')
    E('HZERO', 0, rPL1)
    E('LDI', 27, 0, 0, 1)
    E('HREG', 0, 27, 0, 1)
    hram_c(A_KEY, rN)
    E('LDI', 27, 0, 0, A_PAIR)
    E('HT1', 0, 27, r2N, 0)
    E('MOV', rDEST, 30)
    E('CALL', imm=0, target='XMSS_HGO')
    E('RET')
