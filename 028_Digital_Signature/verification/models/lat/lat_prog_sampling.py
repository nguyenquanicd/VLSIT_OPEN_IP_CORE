"""Samplers of the lattice processor programs: SAMPLE_A, EXPAND_S, EXPAND_MASK, SAMPLE_BALL. Every hash job has a fixed output
length that covers the rejection sampling with a probability of failure far below 2^-128; the unread part is drained."""
from ltp_isa import *
from lat_prog import *


def emit_sampling(p):
    E, L = p.E, p.L

    # SAMPLE_A: R0 = destination, R1 = row r, R2 = column s. SHAKE128(rho || s || r), 3 bytes per candidate.
    # SAMPLE_M (PARA_EN_DPA_PQ): the same rejection sampling from the mask seed: a uniform polynomial modulo q.
    for lab, seed in (('L_SAMPLE_A', SCR_RHO), ('L_SAMPLE_M', SCR_MSEED)):
        L(lab)
        p.ldi(3, 4032)
        E('XSTART', 0, 3, 0, H_SHAKE128)
        p.ldi(4, 0)
        p.ldi(6, 32)
        L(lab + '_R')
        p.lw(5, 4, seed)
        E('XPUT', 0, 5)
        p.loop_lt(4, 6, lab + '_R')
        E('XPUT', 0, 2)
        E('XPUT', 0, 1)
        E('XFIN')
        p.ldi(4, 0)
        L(lab + '_S')
        E('XGET', 5)
        E('XGET', 6)
        E('XGET', 7)
        p.andi(7, 7, 0x7F)
        p.shli(6, 6, 8)
        E('OR', 5, 5, 6)
        p.shli(7, 7, 16)
        E('OR', 5, 5, 7)
        p.ldi(8, Q)
        p.ltu(2, 5, 8)
        p.brn(2, lab + '_S')
        p.add(9, 0, 4)
        p.sw(9, 5)
        p.addi(4, 4, 1)
        p.ldi(8, 256)
        p.ltu(2, 4, 8)
        p.brf(2, lab + '_S')
        E('XDRAIN')
        p.ret()

    # EXPAND_S: R0 = destination, R1 = nonce. SHAKE256(rho' || nonce (2 bytes)), nibbles with the bound eta.
    L('L_EXPAND_S')
    p.ldi(3, 1088)
    E('XSTART', 0, 3, 0, H_SHAKE256)
    p.ldi(4, 0)
    p.ldi(6, 64)
    L('L_EXPAND_S_R')
    p.lw(5, 4, SCR_RHO2)
    E('XPUT', 0, 5)
    p.loop_lt(4, 6, 'L_EXPAND_S_R')
    E('XPUT', 0, 1)
    p.shri(5, 1, 8)
    E('XPUT', 0, 5)
    E('XFIN')
    p.ldi(4, 0)                        # coefficients done
    L('L_EXPAND_S_B')
    E('XGET', 5)                       # byte
    p.ldi(6, 0)                        # nibble number
    L('L_EXPAND_S_N')
    p.ldi(8, 256)
    p.ltu(2, 4, 8)
    p.brn(2, 'L_EXPAND_S_E')
    p.andi(7, 5, 15)
    p.eqi(3, gETA, 2)
    p.brf(3, 'L_EXPAND_S_2')
    p.ldi(8, 9)                        # eta = 4: accept z < 9, coefficient 4 - z
    p.ltu(2, 7, 8)
    p.brn(2, 'L_EXPAND_S_K')
    p.ldi(9, 4)
    p.sub(9, 9, 7)
    p.jmp('L_EXPAND_S_W')
    L('L_EXPAND_S_2')
    p.ldi(8, 15)                       # eta = 2: accept z < 15, coefficient 2 - (z mod 5)
    p.ltu(2, 7, 8)
    p.brn(2, 'L_EXPAND_S_K')
    p.ldi(8, 5)
    E('MODU', 9, 7, 8)
    p.ldi(8, 2)
    p.sub(9, 8, 9)
    L('L_EXPAND_S_W')
    p.shri(8, 9, 31)
    p.eqi(2, 8, 1)
    p.brn(2, 'L_EXPAND_S_P')
    p.ldi(8, Q)
    p.add(9, 9, 8)
    L('L_EXPAND_S_P')
    p.add(8, 0, 4)
    p.sw(8, 9)
    p.addi(4, 4, 1)
    L('L_EXPAND_S_K')
    p.shri(5, 5, 4)
    p.addi(6, 6, 1)
    p.eqi(2, 6, 2)
    p.brn(2, 'L_EXPAND_S_N')
    p.jmp('L_EXPAND_S_B')
    L('L_EXPAND_S_E')
    E('XDRAIN')
    p.ret()

    # EXPAND_MASK: R0 = destination, R1 = nonce. SHAKE256(rho'' || nonce), c bits per coefficient, coefficient gamma1 - v.
    L('L_EXPAND_MASK')
    p.shli(3, gCBITS, 5)
    E('XSTART', 0, 3, 0, H_SHAKE256)
    p.ldi(4, 0)
    p.ldi(6, 64)
    L('L_EXPAND_MASK_R')
    p.lw(5, 4, SCR_RHOPP)
    E('XPUT', 0, 5)
    p.loop_lt(4, 6, 'L_EXPAND_MASK_R')
    E('XPUT', 0, 1)
    p.shri(5, 1, 8)
    E('XPUT', 0, 5)
    E('XFIN')
    p.ldi(7, 1)
    E('SHL', 7, 7, gCBITS)
    p.subi(7, 7, 1)                    # mask of c bits
    p.ldi(4, 0)                        # accumulator
    p.ldi(5, 0)                        # bits in the accumulator
    p.ldi(6, 0)                        # coefficient
    L('L_EXPAND_MASK_C')
    p.ltu(2, 5, gCBITS)
    p.brn(2, 'L_EXPAND_MASK_V')
    E('XGET', 8)
    E('SHL', 8, 8, 5)
    E('OR', 4, 4, 8)
    p.addi(5, 5, 8)
    p.jmp('L_EXPAND_MASK_C')
    L('L_EXPAND_MASK_V')
    E('AND', 8, 4, 7)
    E('SHR', 4, 4, gCBITS)
    p.sub(5, 5, gCBITS)
    p.sub(9, gG1, 8)
    p.shri(8, 9, 31)
    p.eqi(2, 8, 1)
    p.brn(2, 'L_EXPAND_MASK_P')
    p.ldi(8, Q)
    p.add(9, 9, 8)
    L('L_EXPAND_MASK_P')
    p.add(8, 0, 6)
    p.sw(8, 9)
    p.addi(6, 6, 1)
    p.ldi(8, 256)
    p.ltu(2, 6, 8)
    p.brf(2, 'L_EXPAND_MASK_C')
    E('XDRAIN')
    p.ret()

    # SAMPLE_BALL: R0 = destination. c-tilde (gLAM4 bytes at SCR_CT) -> challenge polynomial with tau nonzero coefficients.
    L('L_SAMPLE_BALL')
    p.call('L_PZERO')
    p.ldi(3, 1088)
    E('XSTART', 0, 3, 0, H_SHAKE256)
    p.ldi(4, 0)
    L('L_SAMPLE_BALL_R')
    p.lw(5, 4, SCR_CT)
    E('XPUT', 0, 5)
    p.addi(4, 4, 1)
    p.ltu(2, 4, gLAM4)
    p.brf(2, 'L_SAMPLE_BALL_R')
    E('XFIN')
    p.ldi(6, 0)                        # sign bits 0..31
    p.ldi(7, 0)                        # sign bits 32..63
    for reg in (6, 7):
        for byte in range(4):
            E('XGET', 5)
            if byte:
                p.shli(5, 5, 8 * byte)
            E('OR', reg, reg, 5)
    p.ldi(4, 256)
    p.sub(4, 4, gTAU)                  # i
    L('L_SAMPLE_BALL_I')
    E('XGET', 5)                       # candidate j
    p.ltu(2, 4, 5)
    p.brf(2, 'L_SAMPLE_BALL_I')        # j > i: reject and read the next byte
    p.add(8, 0, 5)
    p.lw(9, 8)
    p.add(3, 0, 4)
    p.sw(3, 9)                         # c[i] = c[j]
    p.add(3, 4, gTAU)
    p.subi(3, 3, 256)                  # sign bit number
    p.ldi(9, 32)
    p.ltu(2, 3, 9)
    p.brf(2, 'L_SAMPLE_BALL_LO')
    p.sub(3, 3, 9)
    E('SHR', 9, 7, 3)
    p.jmp('L_SAMPLE_BALL_B')
    L('L_SAMPLE_BALL_LO')
    E('SHR', 9, 6, 3)
    L('L_SAMPLE_BALL_B')
    p.andi(9, 9, 1)
    p.eqi(2, 9, 1)
    p.ldi(9, 1)
    p.brn(2, 'L_SAMPLE_BALL_S')
    p.ldi(9, Q - 1)
    L('L_SAMPLE_BALL_S')
    p.sw(8, 9)                         # c[j] = +1 or -1
    p.addi(4, 4, 1)
    p.ldi(3, 256)
    p.ltu(2, 4, 3)
    p.brf(2, 'L_SAMPLE_BALL_I')
    E('XDRAIN')
    p.ret()
