"""ML-DSA programs of the lattice processor: key generation, signing, verification and verify-after-sign.
Big subroutines use R10..R13 (and R14, R15 on the final output stage); the programs keep their state in R14..R18."""
from ltp_isa import *
from lat_prog import *

rPOS = 13
Z0 = 9                                   # register that holds 0 (area MSG) for BLB in the subroutines that need it


def emit_main(p):
    E, L = p.E, p.L

    def poly_addr(rd, idx_reg=None, base=0, extra=None):
        """rd = (base + idx_reg + extra) * 256"""
        if idx_reg is None:
            p.ldi(rd, base << 8)
            return
        p.addi(rd, idx_reg, base)
        if extra is not None:
            p.add(rd, rd, extra)
        p.shli(rd, rd, 8)

    def read_bytes(count, scr, counter=10):
        """Reads `count` (register) squeezed bytes into the scratch words at scr."""
        p.ldi(counter, 0)
        lab = 'RB_%d' % len(p.a.code)
        p.L(lab)
        E('XGET', 2)
        p.sw(counter, 2, scr)
        p.loop_lt(counter, count, lab)

    # ------------------------------------------------------------------ entry and parameters
    L('LAT_START')
    for r, f in zip(range(20, 32), (P_K, P_L, P_ETA, P_TAU, P_G1, P_G2, P_BETA, P_OMEGA, P_LAM4, P_CBITS, P_WBITS, P_ALPHA)):
        E('LDP', r, 0, 0, f)
    E('LDS', 0, 0, 0, S_FORM)
    p.eqi(2, 0, 2)
    p.brf(2, 'LAT_OPUNS')                  # forms 0 (pure) and 1 (pre-hash, HashML-DSA) are built
    p.eqi(2, 0, 3)
    p.brf(2, 'LAT_OPUNS')
    E('LDS', 0, 0, 0, S_OP)
    p.eqi(2, 0, 0)
    p.brf(2, 'LAT_KEYGEN')
    p.eqi(2, 0, 1)
    p.brf(2, 'LAT_SIGN')
    p.eqi(2, 0, 2)
    p.brf(2, 'LAT_VERIFY')
    L('LAT_OPUNS')
    E('ERR', 0, 0, 0, 1)

    L('LAT_VAS')                           # verify-after-sign: the data of the signing run is still in the RAM
    for r, f in zip(range(20, 32), (P_K, P_L, P_ETA, P_TAU, P_G1, P_G2, P_BETA, P_OMEGA, P_LAM4, P_CBITS, P_WBITS, P_ALPHA)):
        E('LDP', r, 0, 0, f)
    p.ldi(18, AREA_RES)
    p.jmp('LAT_VCORE')

    # ------------------------------------------------------------------ key generation of the operation
    L('LAT_KEYGEN')
    E('FSET', F_EMIT, 0, 0, 1)
    p.ldi(13, 0)
    p.call('L_KG')
    E('FSET', 7, 0, 0, 1)
    E('END')

    # ------------------------------------------------------------------ KG: A, s1, s2, t1, t0, tr, K
    L('L_KG')
    p.ldi(0, 128)
    E('XSTART', 0, 0, 0, H_SHAKE256)
    p.ldi(10, 0)
    p.ldi(1, 32)
    L('KG_A')
    E('LDK', 2, 10, 0, 0)
    E('XPUT', 0, 2)
    p.loop_lt(10, 1, 'KG_A')
    E('XPUT', 0, gK)
    E('XPUT', 0, gL)
    E('XFIN')
    p.ldi(1, 32)
    read_bytes(1, SCR_RHO)
    p.ldi(1, 64)
    read_bytes(1, SCR_RHO2)
    p.ldi(1, 32)
    read_bytes(1, SCR_K)
    p.call('L_GENA')
    # s1 (NTT domain) and s2 (normal for now)
    p.ldi(11, 0)
    L('KG_S1')
    poly_addr(0, 11, PS1H)
    p.mov(1, 11)
    p.call('L_EXPAND_S')
    poly_addr(0, 11, PS1H)
    p.call('L_NTT')
    p.loop_lt(11, gL, 'KG_S1')
    p.ldi(11, 0)
    L('KG_S2')
    poly_addr(0, 11, PS2H)
    p.add(1, 11, gL)
    p.call('L_EXPAND_S')
    p.loop_lt(11, gK, 'KG_S2')
    # t = INTT(A s1) + s2, split into t1 and t0
    p.ldi(11, 0)
    L('KG_T')
    poly_addr(0, None, PTMP)
    p.call('L_PZERO')
    p.ldi(12, 0)
    L('KG_TS')
    poly_addr(0, None, PTMP)
    E('MULL', 3, 11, gL)
    p.add(3, 3, 12)
    p.addi(3, 3, PA)
    p.shli(1, 3, 8)
    poly_addr(2, 12, PS1H)
    p.call('L_PMAC')
    p.loop_lt(12, gL, 'KG_TS')
    poly_addr(0, None, PTMP)
    p.call('L_INTT')
    poly_addr(0, None, PTMP)
    poly_addr(1, None, PTMP)
    poly_addr(2, 11, PS2H)
    p.call('L_PADD')
    p.ldi(10, 0)
    L('KG_P2R')
    poly_addr(3, None, PTMP)
    p.add(3, 3, 10)
    p.lw(7, 3)                         # r+
    p.andi(8, 7, 8191)
    p.shri(9, 7, 13)
    p.ldi(6, 4096)
    p.ltu(2, 6, 8)
    p.brn(2, 'KG_P2R_S')
    p.addi(9, 9, 1)
    p.subi(8, 8, 8192)
    p.ldi(6, Q)
    p.add(8, 8, 6)
    L('KG_P2R_S')
    poly_addr(3, 11, PT1)
    p.add(3, 3, 10)
    p.sw(3, 9)
    poly_addr(3, 11, PT0H)
    p.add(3, 3, 10)
    p.sw(3, 8)
    p.addi(10, 10, 1)
    p.ldi(6, 256)
    p.ltu(2, 10, 6)
    p.brf(2, 'KG_P2R')
    p.loop_lt(11, gK, 'KG_T')
    p.ldi(11, 0)
    L('KG_N')
    poly_addr(0, 11, PS2H)
    p.call('L_NTT')
    poly_addr(0, 11, PT0H)
    p.call('L_NTT')
    p.loop_lt(11, gK, 'KG_N')
    # tr = SHAKE256(pk, 64); the public key goes to the buffer when F6 is set
    p.ldi(0, 64)
    E('XSTART', 0, 0, 0, H_SHAKE256)
    p.ldi(10, 0)
    p.ldi(1, 32)
    L('KG_TR_R')
    p.lw(0, 10, SCR_RHO)
    p.call('L_HB')
    p.loop_lt(10, 1, 'KG_TR_R')
    p.ldi(11, 0)
    L('KG_TR_P')
    p.ldi(10, 0)
    L('KG_TR_G')
    poly_addr(3, 11, PT1)
    p.add(3, 3, 10)
    p.lw(4, 3, 0)
    p.lw(5, 3, 1)
    p.lw(6, 3, 2)
    p.lw(7, 3, 3)
    p.andi(0, 4, 255)
    p.call('L_HB')
    p.shri(0, 4, 8)
    p.shli(8, 5, 2)
    E('OR', 0, 0, 8)
    p.andi(0, 0, 255)
    p.call('L_HB')
    p.shri(0, 5, 6)
    p.shli(8, 6, 4)
    E('OR', 0, 0, 8)
    p.andi(0, 0, 255)
    p.call('L_HB')
    p.shri(0, 6, 4)
    p.shli(8, 7, 6)
    E('OR', 0, 0, 8)
    p.andi(0, 0, 255)
    p.call('L_HB')
    p.shri(0, 7, 2)
    p.call('L_HB')
    p.addi(10, 10, 4)
    p.ldi(6, 256)
    p.ltu(2, 10, 6)
    p.brf(2, 'KG_TR_G')
    p.loop_lt(11, gK, 'KG_TR_P')
    E('XFIN')
    p.ldi(1, 64)
    read_bytes(1, SCR_TR)
    p.ret()

    # HB: R0 = byte, absorbed; written to the buffer result area at R13 when F6 is set (R13 advances then)
    L('L_HB')
    E('XPUT', 0, 0)
    p.brn(F_EMIT, 'L_HB_E')
    E('BSB', 0, rPOS, 0, AREA_RES)
    p.addi(rPOS, rPOS, 1)
    L('L_HB_E')
    p.ret()

    # MU: SCR_MU = SHAKE256(tr || M', 64), M' = form || len(ctx) || ctx || [OID of the hash] || M with the context stored
    # after the message; form 0 is ML-DSA (FIPS 204 algorithm 2), form 1 HashML-DSA (algorithm 4, M is the digest PH(M))
    L('L_MU')
    p.ldi(0, 64)
    E('XSTART', 0, 0, 0, H_SHAKE256)
    p.ldi(10, 0)
    p.ldi(1, 64)
    L('MU_TR')
    p.lw(2, 10, SCR_TR)
    E('XPUT', 0, 2)
    p.loop_lt(10, 1, 'MU_TR')
    E('LDS', 2, 0, 0, S_FORM)
    E('XPUT', 0, 2)
    E('LDS', 3, 0, 0, S_LEN_CTX)
    E('XPUT', 0, 3)
    E('LDS', 4, 0, 0, S_LEN_MSG)
    p.ldi(Z0, AREA_MSG)
    p.ldi(10, 0)
    L('MU_C')
    p.ltu(2, 10, 3)
    p.brn(2, 'MU_M0')
    p.add(5, 4, 10)
    E('BLB', 6, 5, Z0, 0)
    E('XPUT', 0, 6)
    p.addi(10, 10, 1)
    p.jmp('MU_C')
    L('MU_M0')
    # DER encoding of the OID of the hash of dsig_op.hash: 2.16.840.1.101.3.4.2.x with x = 1, 2, 3 (SHA-256, SHA-384,
    # SHA-512) and 8, 9, 10 (SHA3-256, SHA3-384, SHA3-512)
    E('LDS', 2, 0, 0, S_FORM)
    p.eqi(2, 2, 0)
    p.brf(2, 'MU_M00')
    for b in (0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02):
        p.ldi(2, b)
        E('XPUT', 0, 2)
    E('LDS', 2, 0, 0, S_HASH)
    p.ldi(5, 3)
    p.ltu(3, 2, 5)
    p.addi(2, 2, 1)
    p.brf(3, 'MU_OID')
    p.addi(2, 2, 4)
    L('MU_OID')
    E('XPUT', 0, 2)
    L('MU_M00')
    p.ldi(10, 0)
    L('MU_M')
    p.ltu(2, 10, 4)
    p.brn(2, 'MU_E')
    E('BLB', 6, 10, Z0, 0)
    E('XPUT', 0, 6)
    p.addi(10, 10, 1)
    p.jmp('MU_M')
    L('MU_E')
    E('XFIN')
    p.ldi(1, 64)
    read_bytes(1, SCR_MU)
    p.ret()

    # W1HASH: SCR_CT = SHAKE256(mu || w1Encode(HighBits(w)), lam/4) over the polynomials PW (sign) or the stream of verify
    L('L_W1HASH')
    E('MOV', 0, gLAM4)
    E('XSTART', 0, 0, 0, H_SHAKE256)
    p.ldi(10, 0)
    p.ldi(1, 64)
    L('W1_MU')
    p.lw(2, 10, SCR_MU)
    E('XPUT', 0, 2)
    p.loop_lt(10, 1, 'W1_MU')
    p.ldi(12, 0)                       # accumulator
    p.ldi(13, 0)                       # bits in it
    p.ldi(10, 0)
    L('W1_R')
    p.ldi(11, 0)
    L('W1_J')
    poly_addr(3, 10, PW)
    p.add(3, 3, 11)
    p.lw(8, 3)
    p.call('L_DECOMP')
    p.call('L_W1PACK')
    p.addi(11, 11, 1)
    p.ldi(6, 256)
    p.ltu(2, 11, 6)
    p.brf(2, 'W1_J')
    p.loop_lt(10, gK, 'W1_R')
    E('XFIN')
    read_bytes(gLAM4, SCR_CT)
    p.ret()

    # W1PACK: R1 = coefficient of w1; R12 accumulator, R13 bit count; absorbed as bytes
    L('L_W1PACK')
    E('SHL', 2, 1, 13)
    E('OR', 12, 12, 2)
    p.add(13, 13, gWBITS)
    L('W1PACK_L')
    p.ldi(4, 8)
    p.ltu(2, 13, 4)
    p.brf(2, 'W1PACK_E')
    p.andi(3, 12, 255)
    E('XPUT', 0, 3)
    p.shri(12, 12, 8)
    p.subi(13, 13, 8)
    p.jmp('W1PACK_L')
    L('W1PACK_E')
    p.ret()

