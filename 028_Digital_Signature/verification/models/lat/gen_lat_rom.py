"""Generates rtl/m_vlsit_dsig_lat_rom.sv: the program ROM, the zeta table, the parameter table and the entry addresses of the
lattice engine, from lat_prog*.py (tested by test_lat_subs.py and test_lat_prog.py).
Usage: python gen_lat_rom.py <output .sv>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ltp_isa import *
import lat_prog as P
import lat_prog_sampling as PS
import lat_prog_main as PM
import lat_prog_sign as PG
import lat_prog_verify as PV


def program():
    a = Asm()
    p = P.Prog(a)
    PM.emit_main(p)
    P.emit_subs(p)
    PS.emit_sampling(p)
    PG.emit_sign(p)
    PV.emit_verify(p)
    return a


def encode(ins):
    op, rd, ra, rb, imm = ins
    assert 0 <= imm < (1 << 43), (op, imm)
    return (OPC[op] << 58) | (rd << 53) | (ra << 48) | (rb << 43) | imm


def main(path):
    a = program()
    code = a.resolve(0)
    words = [encode(i) for i in code]
    n = len(words)
    assert n < 4096
    pt = param_table()
    L = ['/*',
         ' * Generated by verification/models/lat/gen_lat_rom.py from lat_prog*.py; do not edit by hand. Program ROM, zeta table,',
         ' * parameter table and entry addresses of the lattice engine m_vlsit_dsig_lat. %d instructions of 64 bits.' % n,
         ' */',
         '`timescale 1ns/1ps', '',
         'module m_vlsit_dsig_lat_rom (',
         '  input  wire  [11:0]  i_pc,',
         '  output logic [63:0]  o_ins,',
         '  input  wire  [7:0]   i_z,',
         '  output logic [22:0]  o_zeta,',
         '  input  wire  [3:0]   i_alg,',
         '  input  wire  [3:0]   i_field,',
         '  output logic [31:0]  o_val,',
         '  input  wire          i_which,',
         '  output logic [11:0]  o_entry',
         ');', '', '  // Program ROM', '  always_comb begin : p_com_rom', '    case (i_pc)']
    for i, w in enumerate(words):
        L.append("      12'd%d: o_ins = 64'h%016x;" % (i, w))
    L += ["      default: o_ins = 64'd0;", '    endcase', '  end', '',
          '  // Entry address: 0 start of the operation, 1 verify-after-sign', '  always_comb begin : p_com_entry', '    case (i_which)',
          "      1'b0: o_entry = 12'd%d;" % a.labels['LAT_START'],
          "      default: o_entry = 12'd%d;" % a.labels['LAT_VAS'], '    endcase', '  end', '',
          '  // Powers of zeta in bit-reversed order (FIPS 204 appendix B)', '  always_comb begin : p_com_zeta', '    case (i_z)']
    for i, z in enumerate(ZETAS):
        L.append("      8'd%d: o_zeta = 23'd%d;" % (i, z))
    L += ["      default: o_zeta = 23'd0;", '    endcase', '  end', '',
          '  // Parameters of the ML-DSA set (alg 9 ML-DSA-44, 10 ML-DSA-65, 11 ML-DSA-87)', '  always_comb begin : p_com_par',
          "    o_val = 32'd0;", '    case ({i_alg, i_field})']
    for alg, fields in sorted(pt.items()):
        for f, v in sorted(fields.items()):
            L.append("      {4'd%d, 4'd%d}: o_val = 32'd%d;" % (alg, f, v))
    L += ["      default: o_val = 32'd0;", '    endcase', '  end', '', 'endmodule']
    open(path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'common'))
    import rom_postfix
    rom_postfix.finish(path)
    print('%d instructions' % n, {k: v for k, v in a.labels.items() if k in ('LAT_START', 'LAT_VAS')})


if __name__ == '__main__':
    sys.exit(main(sys.argv[1]))
