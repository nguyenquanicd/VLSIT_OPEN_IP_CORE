"""ML-DSA verification program of the lattice processor (FIPS 204 algorithm 8, pure form) and the public key loader.
LAT_VERIFY: public key and signature from the buffer; LAT_VCORE (R18 = area of the signature) is also the verify-after-sign
entry of LAT_VAS with the data of the signing run still in the RAM."""
from ltp_isa import *
from lat_prog import *


def emit_verify(p):
    E, L = p.E, p.L

    def poly_addr(rd, idx_reg=None, base=0):
        if idx_reg is None:
            p.ldi(rd, base << 8)
            return
        p.addi(rd, idx_reg, base)
        p.shli(rd, rd, 8)

    def read_bytes(count, scr, counter=10):
        p.ldi(counter, 0)
        lab = 'RBV_%d' % len(p.a.code)
        p.L(lab)
        E('XGET', 2)
        p.sw(counter, 2, scr)
        p.loop_lt(counter, count, lab)

    # LOADPK: rho, t1 and tr = SHAKE256(pk, 64) from the public key in the buffer
    L('L_LOADPK')
    p.ldi(0, 64)
    E('XSTART', 0, 0, 0, H_SHAKE256)
    p.ldi(9, AREA_PK)
    p.ldi(10, 0)
    p.ldi(1, 32)
    L('LP_R')
    E('BLB', 2, 10, 9, 0)
    E('XPUT', 0, 2)
    p.sw(10, 2, SCR_RHO)
    p.loop_lt(10, 1, 'LP_R')
    p.ldi(11, 0)
    L('LP_P')
    p.ldi(10, 0)
    L('LP_G')
    p.ldi(19, 320)
    E('MULL', 14, 11, 19)
    p.addi(14, 14, 32)
    p.shri(19, 10, 2)
    p.shli(15, 19, 2)
    p.add(19, 15, 19)
    p.add(14, 14, 19)
    for k in range(5):
        E('BLB', 2 + k, 14, 9, k)
    for k in range(5):
        E('XPUT', 0, 2 + k)
    p.andi(7, 3, 3)
    p.shli(7, 7, 8)
    E('OR', 0, 2, 7)                   # c0
    p.shri(1, 3, 2)
    p.andi(7, 4, 15)
    p.shli(7, 7, 6)
    E('OR', 1, 1, 7)                   # c1
    p.shri(7, 4, 4)
    p.andi(19, 5, 63)
    p.shli(19, 19, 4)
    E('OR', 7, 7, 19)                  # c2
    p.shri(8, 5, 6)
    p.shli(19, 6, 2)
    E('OR', 8, 8, 19)                  # c3
    p.addi(19, 11, PT1)
    p.shli(19, 19, 8)
    p.add(19, 19, 10)
    p.sw(19, 0, 0)
    p.sw(19, 1, 1)
    p.sw(19, 7, 2)
    p.sw(19, 8, 3)
    p.addi(10, 10, 4)
    p.ldi(19, 256)
    p.ltu(2, 10, 19)
    p.brf(2, 'LP_G')
    p.loop_lt(11, gK, 'LP_P')
    E('XFIN')
    p.ldi(1, 64)
    read_bytes(1, SCR_TR)
    p.ret()

    # ------------------------------------------------------------------ verification
    L('LAT_VERIFY')
    p.ldi(18, AREA_SIG)
    p.call('L_LOADPK')
    p.call('L_GENA')
    L('LAT_VCORE')
    # c-tilde from the signature
    p.ldi(10, 0)
    L('VC_C')
    E('BLB', 2, 10, 18, 0)
    p.sw(10, 2, SCR_CT)
    p.sw(10, 2, SCR_CT2)
    p.loop_lt(10, gLAM4, 'VC_C')
    # z: c bits per coefficient, coefficient gamma1 - v; the bound of the norm is checked at once
    p.mov(14, gLAM4)
    p.ldi(15, 1)
    E('SHL', 15, 15, gCBITS)
    p.subi(15, 15, 1)
    p.ldi(10, 0)
    L('VC_ZR')
    p.ldi(12, 0)
    p.ldi(13, 0)
    p.ldi(11, 0)
    L('VC_ZJ')
    p.ltu(2, 13, gCBITS)
    p.brn(2, 'VC_ZV')
    E('BLB', 2, 14, 18, 0)
    E('SHL', 2, 2, 13)
    E('OR', 12, 12, 2)
    p.addi(13, 13, 8)
    p.addi(14, 14, 1)
    p.jmp('VC_ZJ')
    L('VC_ZV')
    E('AND', 2, 12, 15)
    E('SHR', 12, 12, gCBITS)
    p.sub(13, 13, gCBITS)
    p.sub(3, gG1, 2)
    p.shri(4, 3, 31)
    p.eqi(2, 4, 1)
    p.brn(2, 'VC_ZP')
    p.ldi(4, Q)
    p.add(3, 3, 4)
    L('VC_ZP')
    p.addi(5, 10, PY)
    p.shli(5, 5, 8)
    p.add(5, 5, 11)
    p.sw(5, 3)
    p.addi(11, 11, 1)
    p.ldi(4, 256)
    p.ltu(2, 11, 4)
    p.brf(2, 'VC_ZJ')
    poly_addr(0, 10, PY)
    E('LDP', 1, 0, 0, P_GB)
    p.call('L_NORM')
    p.brf(5, 'VC_FAIL')
    p.loop_lt(10, gL, 'VC_ZR')
    # hint: unpack with the checks of FIPS 204 algorithm 21
    p.ldi(10, 0)
    L('VC_HC')
    poly_addr(0, 10, PH)
    p.call('L_PZERO')
    p.loop_lt(10, gK, 'VC_HC')
    p.ldi(11, 0)
    p.ldi(10, 0)
    L('VC_HI')
    p.add(3, 14, gOMEGA)
    p.add(3, 3, 10)
    E('BLB', 13, 3, 18, 0)             # cumulative count y[omega + i]
    p.ltu(2, 13, 11)
    p.brf(2, 'VC_FAIL')
    p.ltu(2, gOMEGA, 13)
    p.brf(2, 'VC_FAIL')
    p.mov(12, 11)
    L('VC_HL')
    p.ltu(2, 11, 13)
    p.brn(2, 'VC_HD')
    p.add(3, 14, 11)
    E('BLB', 4, 3, 18, 0)              # y[index]
    p.ltu(2, 12, 11)
    p.brn(2, 'VC_HS')
    p.subi(6, 3, 1)
    E('BLB', 5, 6, 18, 0)              # y[index - 1]
    p.ltu(2, 5, 4)
    p.brn(2, 'VC_FAIL')
    L('VC_HS')
    p.addi(5, 10, PH)
    p.shli(5, 5, 8)
    p.add(5, 5, 4)
    p.ldi(6, 1)
    p.sw(5, 6)
    p.addi(11, 11, 1)
    p.jmp('VC_HL')
    L('VC_HD')
    p.loop_lt(10, gK, 'VC_HI')
    L('VC_HZ')
    p.ltu(2, 11, gOMEGA)
    p.brn(2, 'VC_HE')
    p.add(3, 14, 11)
    E('BLB', 4, 3, 18, 0)
    E('ISZ', 2, 4)
    p.brn(2, 'VC_FAIL')
    p.addi(11, 11, 1)
    p.jmp('VC_HZ')
    L('VC_HE')
    p.call('L_MU')
    poly_addr(0, None, PCH)
    p.call('L_SAMPLE_BALL')
    poly_addr(0, None, PCH)
    p.call('L_NTT')
    p.ldi(10, 0)
    L('VC_ZH')
    poly_addr(0, 10, PYH)
    poly_addr(1, 10, PY)
    p.call('L_PCOPY')
    poly_addr(0, 10, PYH)
    p.call('L_NTT')
    p.loop_lt(10, gL, 'VC_ZH')
    p.ldi(10, 0)
    L('VC_T1')
    p.ldi(11, 0)
    L('VC_T1J')
    poly_addr(3, 10, PT1)
    p.add(3, 3, 11)
    p.lw(4, 3)
    p.shli(4, 4, 13)
    poly_addr(3, 10, PT0H)
    p.add(3, 3, 11)
    p.sw(3, 4)
    p.addi(11, 11, 1)
    p.ldi(4, 256)
    p.ltu(2, 11, 4)
    p.brf(2, 'VC_T1J')
    poly_addr(0, 10, PT0H)
    p.call('L_NTT')
    p.loop_lt(10, gK, 'VC_T1')
    # w1' from the approximation of w, hashed with mu
    E('MOV', 0, gLAM4)
    E('XSTART', 0, 0, 0, H_SHAKE256)
    p.ldi(10, 0)
    p.ldi(1, 64)
    L('VC_MU')
    p.lw(2, 10, SCR_MU)
    E('XPUT', 0, 2)
    p.loop_lt(10, 1, 'VC_MU')
    p.ldi(12, 0)
    p.ldi(13, 0)
    p.ldi(10, 0)
    L('VC_W')
    poly_addr(0, None, PTMP)
    p.call('L_PZERO')
    p.ldi(11, 0)
    L('VC_WS')
    poly_addr(0, None, PTMP)
    E('MULL', 3, 10, gL)
    p.add(3, 3, 11)
    p.addi(3, 3, PA)
    p.shli(1, 3, 8)
    poly_addr(2, 11, PYH)
    p.call('L_PMAC')
    p.loop_lt(11, gL, 'VC_WS')
    poly_addr(0, None, PCT)
    poly_addr(1, None, PCH)
    poly_addr(2, 10, PT0H)
    p.call('L_PMUL')
    poly_addr(0, None, PTMP)
    poly_addr(1, None, PTMP)
    poly_addr(2, None, PCT)
    p.call('L_PSUB')
    poly_addr(0, None, PTMP)
    p.call('L_INTT')
    E('LDP', 19, 0, 0, P_M)
    p.ldi(14, 0)
    L('VC_WJ')
    poly_addr(3, None, PTMP)
    p.add(3, 3, 14)
    p.lw(8, 3)
    p.call('L_DECOMP')
    poly_addr(3, 10, PH)
    p.add(3, 3, 14)
    p.lw(4, 3)
    p.eqi(2, 4, 1)
    p.brn(2, 'VC_WN')
    p.ldi(3, 0)
    E('LTS', 2, 3, 2)                  # 0 < r0
    p.brf(2, 'VC_WUP')
    E('ISZ', 3, 1)
    p.brf(3, 'VC_WWR')
    p.subi(1, 1, 1)
    p.jmp('VC_WN')
    L('VC_WWR')
    p.subi(1, 19, 1)
    p.jmp('VC_WN')
    L('VC_WUP')
    p.addi(1, 1, 1)
    E('EQ', 3, 1, 19)
    p.brn(3, 'VC_WN')
    p.ldi(1, 0)
    L('VC_WN')
    p.call('L_W1PACK')
    p.addi(14, 14, 1)
    p.ldi(4, 256)
    p.ltu(2, 14, 4)
    p.brf(2, 'VC_WJ')
    p.loop_lt(10, gK, 'VC_W')
    E('XFIN')
    p.ldi(10, 0)
    p.ldi(15, 0)
    L('VC_CMP')
    E('XGET', 2)
    p.lw(3, 10, SCR_CT2)
    E('XOR', 4, 2, 3)
    E('OR', 15, 15, 4)
    p.loop_lt(10, gLAM4, 'VC_CMP')
    E('ISZ', 7, 15)
    E('END')
    L('VC_FAIL')
    E('FSET', 7, 0, 0, 0)
    E('END')
