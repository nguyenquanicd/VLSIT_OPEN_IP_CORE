"""ML-DSA signing program of the lattice processor and the subroutines it needs (GENA, R0CHK, HINTS, OUTSIG)."""
from ltp_isa import *
from lat_prog import *


def emit_sign(p):
    E, L = p.E, p.L

    def poly_addr(rd, idx_reg=None, base=0):
        if idx_reg is None:
            p.ldi(rd, base << 8)
            return
        p.addi(rd, idx_reg, base)
        p.shli(rd, rd, 8)

    def read_bytes(count, scr, counter=10):
        p.ldi(counter, 0)
        lab = 'RBS_%d' % len(p.a.code)
        p.L(lab)
        E('XGET', 2)
        p.sw(counter, 2, scr)
        p.loop_lt(counter, count, lab)

    # GENA: matrix A in the NTT domain from rho (SCR_RHO) at the polynomials PA + r l + s
    L('L_GENA')
    p.ldi(11, 0)
    L('GENA_R')
    p.ldi(12, 0)
    L('GENA_S')
    E('MULL', 3, 11, gL)
    p.add(3, 3, 12)
    p.addi(3, 3, PA)
    p.shli(0, 3, 8)
    p.mov(1, 11)
    p.mov(2, 12)
    p.call('L_SAMPLE_A')
    p.loop_lt(12, gL, 'GENA_S')
    p.loop_lt(11, gK, 'GENA_R')
    p.ret()

    # R0CHK: R0 = polynomial; F5 = 1 when |LowBits| >= gamma2 - beta for some coefficient (R1..R9, R19 are clobbered)
    L('L_R0CHK')
    E('LDP', 19, 0, 0, P_G2B)
    E('FSET', 5, 0, 0, 0)
    p.ldi(9, 0)
    L('R0CHK_L')
    p.add(8, 0, 9)
    p.lw(8, 8)
    p.call('L_DECOMP')
    p.shri(3, 2, 31)
    p.eqi(2, 3, 1)
    p.brn(2, 'R0CHK_P')
    p.ldi(3, 0)
    p.sub(2, 3, 2)
    L('R0CHK_P')
    p.ltu(2, 2, 19)
    p.brf(2, 'R0CHK_K')
    E('FSET', 5, 0, 0, 1)
    p.ret()
    L('R0CHK_K')
    p.addi(9, 9, 1)
    p.ldi(3, 256)
    p.ltu(2, 9, 3)
    p.brf(2, 'R0CHK_L')
    p.ret()

    # HINTS: R10 = ct0 polynomial, R11 = w - c s2 polynomial, R12 = hint polynomial (0 or 1 per coefficient);
    # R17 += number of hints. h = HighBits(w - cs2 + ct0) != HighBits(w - cs2).
    L('L_HINTS')
    p.ldi(13, 0)
    L('HINTS_L')
    p.add(3, 10, 13)
    p.lw(4, 3)
    p.add(3, 11, 13)
    p.lw(8, 3)
    E('ADDQ', 14, 8, 4)
    p.call('L_DECOMP')
    p.mov(15, 1)
    p.mov(8, 14)
    p.call('L_DECOMP')
    E('EQ', 2, 1, 15)
    p.ldi(3, 0)
    p.brf(2, 'HINTS_S')
    p.ldi(3, 1)
    p.addi(17, 17, 1)
    L('HINTS_S')
    p.add(4, 12, 13)
    p.sw(4, 3)
    p.addi(13, 13, 1)
    p.ldi(4, 256)
    p.ltu(2, 13, 4)
    p.brf(2, 'HINTS_L')
    p.ret()

    # ------------------------------------------------------------------ signing
    L('LAT_SIGN')
    E('FSET', F_EMIT, 0, 0, 0)
    p.call('L_KG')
    p.call('L_MU')
    p.ldi(0, 64)
    E('XSTART', 0, 0, 0, H_SHAKE256)
    p.ldi(10, 0)
    p.ldi(1, 32)
    L('SG_K')
    p.lw(2, 10, SCR_K)
    E('XPUT', 0, 2)
    p.loop_lt(10, 1, 'SG_K')
    E('LDS', 3, 0, 0, S_HEDGED)
    p.eqi(4, 3, 1)
    p.ldi(10, 0)
    L('SG_RND')
    p.ldi(2, 0)
    p.brn(4, 'SG_RND0')
    E('LDR', 2, 10, 0, 0)
    L('SG_RND0')
    E('XPUT', 0, 2)
    p.loop_lt(10, 1, 'SG_RND')
    p.ldi(10, 0)
    p.ldi(1, 64)
    L('SG_MU')
    p.lw(2, 10, SCR_MU)
    E('XPUT', 0, 2)
    p.loop_lt(10, 1, 'SG_MU')
    E('XFIN')
    p.ldi(1, 64)
    read_bytes(1, SCR_RHOPP)
    p.ldi(16, 0)                       # kappa
    L('SG_ATTEMPT')
    p.ldi(3, 65536)
    p.ltu(2, 16, 3)
    p.brn(2, 'SG_ERR')
    p.ldi(18, 0)
    L('SG_Y')
    p.add(1, 16, 18)
    poly_addr(0, 18, PY)
    p.call('L_EXPAND_MASK')
    poly_addr(0, 18, PYH)
    poly_addr(1, 18, PY)
    p.call('L_PCOPY')
    poly_addr(0, 18, PYH)
    p.call('L_NTT')
    p.loop_lt(18, gL, 'SG_Y')
    p.ldi(18, 0)
    L('SG_W')
    poly_addr(0, None, PTMP)
    p.call('L_PZERO')
    p.ldi(15, 0)
    L('SG_WS')
    poly_addr(0, None, PTMP)
    E('MULL', 3, 18, gL)
    p.add(3, 3, 15)
    p.addi(3, 3, PA)
    p.shli(1, 3, 8)
    poly_addr(2, 15, PYH)
    p.call('L_PMAC')
    p.loop_lt(15, gL, 'SG_WS')
    poly_addr(0, None, PTMP)
    p.call('L_INTT')
    poly_addr(0, 18, PW)
    poly_addr(1, None, PTMP)
    p.call('L_PCOPY')
    p.loop_lt(18, gK, 'SG_W')
    p.call('L_W1HASH')
    poly_addr(0, None, PCH)
    p.call('L_SAMPLE_BALL')
    poly_addr(0, None, PCH)
    p.call('L_NTT')
    p.ldi(18, 0)
    L('SG_Z')
    poly_addr(0, None, PTMP)
    poly_addr(1, None, PCH)
    poly_addr(2, 18, PS1H)
    p.call('L_PMUL')
    poly_addr(0, None, PTMP)
    p.call('L_INTT')
    poly_addr(0, 18, PY)
    poly_addr(1, 18, PY)
    poly_addr(2, None, PTMP)
    p.call('L_PADD')
    poly_addr(0, 18, PY)
    E('LDP', 1, 0, 0, P_GB)
    p.call('L_NORM')
    p.brf(5, 'SG_REJECT')
    p.loop_lt(18, gL, 'SG_Z')
    p.ldi(18, 0)
    L('SG_R0')
    poly_addr(0, None, PTMP)
    poly_addr(1, None, PCH)
    poly_addr(2, 18, PS2H)
    p.call('L_PMUL')
    poly_addr(0, None, PTMP)
    p.call('L_INTT')
    poly_addr(0, 18, PW)
    poly_addr(1, 18, PW)
    poly_addr(2, None, PTMP)
    p.call('L_PSUB')
    poly_addr(0, 18, PW)
    p.call('L_R0CHK')
    p.brf(5, 'SG_REJECT')
    p.loop_lt(18, gK, 'SG_R0')
    p.ldi(17, 0)
    p.ldi(18, 0)
    L('SG_H')
    poly_addr(0, None, PTMP)
    poly_addr(1, None, PCH)
    poly_addr(2, 18, PT0H)
    p.call('L_PMUL')
    poly_addr(0, None, PTMP)
    p.call('L_INTT')
    poly_addr(0, None, PTMP)
    p.mov(1, gG2)
    p.call('L_NORM')
    p.brf(5, 'SG_REJECT')
    poly_addr(10, None, PTMP)
    poly_addr(11, 18, PW)
    poly_addr(12, 18, PH)
    p.call('L_HINTS')
    p.loop_lt(18, gK, 'SG_H')
    p.ltu(2, gOMEGA, 17)
    p.brf(2, 'SG_REJECT')
    p.call('L_OUTSIG')
    E('FSET', 7, 0, 0, 1)
    E('END')
    L('SG_REJECT')
    p.add(16, 16, gL)
    p.jmp('SG_ATTEMPT')
    L('SG_ERR')
    E('ERR', 0, 0, 0, 4)

    # OUTSIG: signature = c-tilde || z || hint to the buffer result area.
    # R10 r, R11 j, R12 accumulator, R13 bits, R14 position, R15 hint index, R8 start of the hint area
    L('L_OUTSIG')
    p.ldi(14, 0)
    p.ldi(10, 0)
    L('OS_C')
    p.lw(2, 10, SCR_CT)
    E('BSB', 0, 14, 2, AREA_RES)
    p.addi(14, 14, 1)
    p.addi(10, 10, 1)
    p.ltu(2, 10, gLAM4)
    p.brf(2, 'OS_C')
    p.ldi(12, 0)
    p.ldi(13, 0)
    p.ldi(10, 0)
    L('OS_ZR')
    p.ldi(11, 0)
    L('OS_ZJ')
    poly_addr(3, 10, PY)
    p.add(3, 3, 11)
    p.lw(4, 3)                         # z coefficient in [0, q)
    p.ldi(5, (Q - 1) // 2)
    p.ltu(2, 5, 4)
    p.brn(2, 'OS_ZP')
    p.ldi(5, Q)
    p.sub(5, 5, 4)
    E('ADD', 5, gG1, 5)                # gamma1 + (q - z)
    p.jmp('OS_ZV')
    L('OS_ZP')
    p.sub(5, gG1, 4)                   # gamma1 - z
    L('OS_ZV')
    E('SHL', 5, 5, 13)
    E('OR', 12, 12, 5)
    p.add(13, 13, gCBITS)
    L('OS_ZB')
    p.ldi(6, 8)
    p.ltu(2, 13, 6)
    p.brf(2, 'OS_ZN')
    p.andi(7, 12, 255)
    E('BSB', 0, 14, 7, AREA_RES)
    p.addi(14, 14, 1)
    p.shri(12, 12, 8)
    p.subi(13, 13, 8)
    p.jmp('OS_ZB')
    L('OS_ZN')
    p.addi(11, 11, 1)
    p.ldi(6, 256)
    p.ltu(2, 11, 6)
    p.brf(2, 'OS_ZJ')
    p.loop_lt(10, gL, 'OS_ZR')
    # hint: omega + k bytes, zero filled, then the indexes and the counts
    p.add(9, gOMEGA, gK)
    p.ldi(10, 0)
    p.ldi(2, 0)
    p.mov(8, 14)
    L('OS_HZ')
    p.add(3, 8, 10)
    E('BSB', 0, 3, 2, AREA_RES)
    p.loop_lt(10, 9, 'OS_HZ')
    p.ldi(15, 0)
    p.ldi(10, 0)
    L('OS_HR')
    p.ldi(11, 0)
    L('OS_HJ')
    poly_addr(3, 10, PH)
    p.add(3, 3, 11)
    p.lw(4, 3)
    p.eqi(2, 4, 1)
    p.brn(2, 'OS_HN')
    p.add(3, 8, 15)
    E('BSB', 0, 3, 11, AREA_RES)
    p.addi(15, 15, 1)
    L('OS_HN')
    p.addi(11, 11, 1)
    p.ldi(6, 256)
    p.ltu(2, 11, 6)
    p.brf(2, 'OS_HJ')
    p.add(3, 8, gOMEGA)
    p.add(3, 3, 10)
    E('BSB', 0, 3, 15, AREA_RES)
    p.loop_lt(10, gK, 'OS_HR')
    p.ret()
