"""Generates rtl/m_vlsit_dsig_ec_rom.sv: the program ROM, the constant tables and the entry table of the
elliptic-curve engine, from the programs of ec_progs.py (tested by test_ec_model.py).

Curve numbers: 0 Ed25519, 1 Ed448, 2 P-256, 3 P-384, 4 P-521, 5 secp256k1, 6 Ed25519 with the dom2 prefix (Ed25519ctx, Ed25519ph).
Operation numbers: 0 key generation, 1 signing, 2 verification, 3 verify-after-sign.
Usage: python gen_ec_rom.py <output .sv>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ec_curves import CURVES
from ec_isa import OPC
import ec_progs as P

CURVE_NO = [('Ed25519', 0), ('Ed448', 1), ('P-256', 2), ('P-384', 3), ('P-521', 4), ('secp256k1', 5), ('Ed25519dom', 6)]
OPS_NO = {'keygen': 0, 'sign': 1, 'verify': 2, 'vas': 3}
CNAMES = ['P', 'N', 'NM1', 'A', 'B', 'B3', 'D', 'GX', 'GY', 'GT', 'PM2', 'NM2', 'P58', 'P34', 'SQRTM1', 'CLAMP_AND', 'CLAMP_OR',
          'MASKY', 'HIFACTOR', 'TWO576', 'IDENT0', 'IDENT1', 'IDENT2', 'IDENT3', 'NBITS', 'PBITS']
CID = {n: i for i, n in enumerate(CNAMES)}


def program(cname, op):
    c = CURVES['Ed25519' if cname == 'Ed25519dom' else cname]
    if cname == 'Ed25519dom':
        return P.prog_ed(c, 'verify' if op in ('verify', 'vas') else op, vas=(op == 'vas'), dom=True)
    if cname == 'Ed25519':
        return P.prog_ed(c, 'verify' if op in ('verify', 'vas') else op, vas=(op == 'vas'))
    if cname == 'Ed448':
        return P.prog_ed448(c, 'verify' if op in ('verify', 'vas') else op, vas=(op == 'vas'))
    return P.prog_ecdsa(c, 'verify' if op in ('verify', 'vas') else op, vas=(op == 'vas'))


def encode(ins):
    op, rd, ra, rb, imm = ins
    if op == 'LDC':
        imm = CID[imm]
    assert 0 <= imm < (1 << 43), (op, imm)
    return (OPC[op] << 58) | (rd << 53) | (ra << 48) | (rb << 43) | imm


def main(path):
    words = []
    entry = {}
    for cname, cno in CURVE_NO:
        for op, ono in OPS_NO.items():
            asm = program(cname, op)
            base = len(words)
            code = asm.resolve(base)
            entry[(cno, ono)] = base + asm.labels['START']
            words += [encode(i) for i in code]
    n = len(words)
    L = []
    L.append('/*')
    L.append(' * Generated by verification/models/ec/gen_ec_rom.py from ec_progs.py; do not edit by hand.')
    L.append(' * Program ROM, constant tables and entry table of the elliptic-curve engine m_vlsit_dsig_ec.')
    L.append(' * %d instructions of 64 bits; curves 0 Ed25519, 1 Ed448, 2 P-256, 3 P-384, 4 P-521, 5 secp256k1, 6 Ed25519 with dom2;' % n)
    L.append(' * operations 0 key generation, 1 signing, 2 verification, 3 verify-after-sign.')
    L.append(' */')
    L.append('`timescale 1ns/1ps')
    L.append('')
    L.append('module m_vlsit_dsig_ec_rom (')
    L.append('  input  wire  [12:0]  i_pc,')
    L.append('  output logic [63:0]  o_ins,')
    L.append('  input  wire  [2:0]   i_curve,')
    L.append('  input  wire  [4:0]   i_cid,')
    L.append('  output logic [575:0] o_const,')
    L.append('  input  wire  [1:0]   i_op,')
    L.append('  output logic [12:0]  o_entry,')
    L.append('  input  wire  [3:0]   i_str_id,')
    L.append('  output logic [255:0] o_str,')
    L.append('  output logic [7:0]   o_str_len')
    L.append(');')
    L.append('')
    L.append('  // Program ROM')
    L.append('  always_comb begin : p_com_rom')
    L.append("    case (i_pc)")
    for i, w in enumerate(words):
        L.append("      13'd%d: o_ins = 64'h%016x;" % (i, w))
    L.append("      default: o_ins = 64'd0;")
    L.append('    endcase')
    L.append('  end')
    L.append('')
    L.append('  // Entry address of the program of an operation')
    L.append('  always_comb begin : p_com_entry')
    L.append("    o_entry = 13'd0;")
    L.append('    case ({i_curve, i_op})')
    for (cno, ono), a in sorted(entry.items()):
        L.append("      {3'd%d, 2'd%d}: o_entry = 13'd%d;" % (cno, ono, a))
    L.append('      default: o_entry = 13\'d0;')
    L.append('    endcase')
    L.append('  end')
    L.append('')
    L.append('  // Constants of the curves (the order of the ids is CNAMES of gen_ec_rom.py)')
    L.append('  always_comb begin : p_com_const')
    L.append("    o_const = 576'd0;")
    L.append('    case ({i_curve, i_cid})')
    for cname, cno in CURVE_NO:
        k = P.consts(CURVES['Ed25519' if cname == 'Ed25519dom' else cname])
        for nme in CNAMES:
            if nme in k:
                v = k[nme]
                L.append("      {3'd%d, 5'd%d}: o_const = 576'h%x;" % (cno, CID[nme], v))
    L.append("      default: o_const = 576'd0;")
    L.append('    endcase')
    L.append('  end')
    L.append('')
    L.append('  // Byte strings: 0 prefix of dom4 (SigEd448), 1 prefix of dom2 (Ed25519ctx, Ed25519ph)')
    L.append('  always_comb begin : p_com_str')
    L.append("    o_str     = 256'd0;")
    L.append("    o_str_len = 8'd0;")
    L.append('    case (i_str_id)')
    for sid in sorted(P.STRINGS):
        s = P.STRINGS[sid]
        L.append("      4'd%d: begin o_str = 256'h%s; o_str_len = 8'd%d; end" % (sid, int.from_bytes(s, 'little').to_bytes(32, 'big').hex(), len(s)))
    L.append("      default: o_str_len = 8'd0;")
    L.append('    endcase')
    L.append('  end')
    L.append('')
    L.append('endmodule')
    open(path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'common'))
    import rom_postfix
    rom_postfix.finish(path)
    print('%d instructions, %d programs' % (n, len(entry)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1]))
